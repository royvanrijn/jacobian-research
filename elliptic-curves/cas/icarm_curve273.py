def on_curve(P):
    x, y = P
    return y*y + x*y == x**3 + A*x + B


def c4():
    return 1 - 48*A


def c6():
    return -1 + 72*A - 864*B


def short_coefficients():
    # Integral short model
    #
    #   Y^2 = X^3 - 27*c4 X - 54*c6
    #
    return (
        Q(0), Q(0), Q(0),
        Q(-27*c4()),
        Q(-54*c6()),
    )


def to_short(P):
    x, y = P
    return (
        36*x + 3,
        108*(2*y + x),
    )



#!/usr/bin/env python3
"""Generate a Magma residual 2/4/8-descent job for the Fermigier rank-20 anchor.

Run this from the jacobian-research repository root, for example:

    python3 elliptic-curves/cas/build_fermigier_rank20_residual_selmer.py \
      --output artifacts/local/elliptic-curves/fermigier_rank20_residual_selmer.m

The generated Magma program:
  * replays the repository's exact 20-point basis,
  * computes TwoDescent relative to that subgroup,
  * computes the Cassels--Tate pairing on the residual quotient,
  * applies FourDescent only to pairing-radical 2-classes,
  * removes the known rank-20 subgroup again during FourDescent,
  * pairs each 4-cover against all residual 2-covers before point search,
  * maps any PointsQI hit back to the original elliptic curve,
  * checks whether 21 points are linearly independent.

It deliberately does not enable GRH class-group bounds.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

CAS_ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(CAS_ROOT))

from build_fermigier_rank20_relative_descent import (  # noqa: E402
    load_selected_points,
    magma_q,
)

KNOWN_RANK = 20


def build_magma(
    model,
    points,
    *,
    point_bound: int,
    pairing_cover_cap: int,
    four_cover_cap: int,
    run_eight_descent: bool,
) -> str:
    coeffs = ", ".join(magma_q(c) for c in model)
    rows = ",\n    ".join(
        f"E![{magma_q(x)}, {magma_q(y)}, 1]" for x, y in points
    )
    eight = "true" if run_eight_descent else "false"

    return f"""// Generated by elliptic-curves/cas/build_fermigier_rank20_residual_selmer.py
// Protocol: R20SEL v1
// No SetClassGroupBounds("GRH") is used: keep the first result unconditional.

Q := Rationals();
E := EllipticCurve([{coeffs}]);
known := [
    {rows}
];

function ExactLog2(n)
    assert n ge 1;
    d := 0;
    m := 1;
    while m lt n do
        m *:= 2;
        d +:= 1;
    end while;
    assert m eq n;
    return d;
end function;

printf "R20SEL|version=1|stage=input|magma=%o|known=%o\\n", GetVersion(), #known;
assert #known eq {KNOWN_RANK};
assert &and[P in E : P in known];

known_independent, known_relation := IsLinearlyIndependent(known);
printf "R20SEL|stage=input_check|known_independent=%o\\n", known_independent;
assert known_independent;

T2, T2map := TwoTorsionSubgroup(E);
t2dim := ExactLog2(#T2);
printf "R20SEL|stage=torsion|two_torsion_order=%o|two_torsion_dim=%o\\n", #T2, t2dim;

// This is the actual relative 2-Selmer experiment. RemoveGens quotients by
// the image of the repository's certified rank-20 subgroup mod 2.
printf "R20SEL|stage=two_descent|status=start\\n";
two_start := Realtime();
covers, maps, quotient_map := TwoDescent(
    E :
    RemoveGens := SequenceToSet(known),
    RemoveTorsion := true
);
two_seconds := Realtime(two_start);

residual_count := #covers;
// TwoDescent lists the nonzero classes in the returned quotient.
residual_dim := ExactLog2(residual_count + 1);
inferred_selmer_dim := {KNOWN_RANK} + t2dim + residual_dim;

printf "R20SEL|stage=two_descent|status=complete|seconds=%o|residual_covers=%o|residual_dim=%o|inferred_selmer_dim=%o\\n",
    two_seconds, residual_count, residual_dim, inferred_selmer_dim;

for i in [1..#covers] do
    f, h := HyperellipticPolynomials(covers[i]);
    printf "R20SEL|stage=two_cover|i=%o|f=%o|h=%o\\n", i, f, h;
end for;

if residual_count eq 0 then
    // The repository already proves rank(E) >= 20. A trivial residual
    // 2-Selmer quotient bounds rank(E) by 20.
    printf "R20SEL|classification=S0_EXACT_RANK20|rank_lower=20|rank_upper=20|reason=trivial_residual_2_selmer\\n";
    quit;
end if;

if residual_count gt {pairing_cover_cap} then
    printf "R20SEL|classification=S4_TOO_MANY_RESIDUAL_COVERS|residual_covers=%o|cap={pairing_cover_cap}|action=use_basis_level_pairing_or_raise_cap\\n",
        residual_count;
    quit;
end if;

// Pair all residual 2-Selmer classes. Any new Mordell--Weil mod-2 class
// must lie in the radical of this pairing.
printf "R20SEL|stage=cassels_tate_2x2|status=start|covers=%o\\n", residual_count;
ct_start := Realtime();
M := ZeroMatrix(Integers(), residual_count, residual_count);
for i in [1..residual_count] do
    for j in [i+1..residual_count] do
        v := CasselsTatePairing(covers[i], covers[j]);
        M[i,j] := v;
        M[j,i] := v;
        printf "R20SEL|stage=cassels_tate_2x2_entry|i=%o|j=%o|value=%o\\n", i, j, v;
    end for;
end for;
ct_seconds := Realtime(ct_start);

radical := [
    i : i in [1..residual_count] |
    &and[M[i,j] eq 0 : j in [1..residual_count]]
];
radical_count := #radical;
radical_dim := ExactLog2(radical_count + 1);
rank_upper_after_pairing := {KNOWN_RANK} + radical_dim;

printf "R20SEL|stage=cassels_tate_2x2|status=complete|seconds=%o|matrix=%o|radical_indices=%o|radical_dim=%o|rank_upper_after_pairing=%o\\n",
    ct_seconds, Eltseq(M), radical, radical_dim, rank_upper_after_pairing;

if radical_dim eq 0 then
    printf "R20SEL|classification=S1_EXACT_RANK20_CT|rank_lower=20|rank_upper=20|reason=residual_selmer_killed_by_cassels_tate\\n";
    quit;
end if;

// Higher descent only on 2-classes in the Cassels--Tate radical.
// Crucial: RemoveGensEC removes the known rank-20 directions AGAIN here.
survivor_four_count := 0;
candidate_count := 0;
empty_four_descents := 0;
capped_four_descents := 0;
obstructed_four_count := 0;
total_four_count := 0;

for i in radical do
    printf "R20SEL|stage=four_descent|status=start|two_cover=%o\\n", i;
    four_start := Realtime();
    fours := FourDescent(
        covers[i] :
        RemoveTorsion := true,
        RemoveGensEC := SequenceToSet(known)
    );
    four_seconds := Realtime(four_start);

    printf "R20SEL|stage=four_descent|status=complete|two_cover=%o|seconds=%o|four_covers=%o\\n",
        i, four_seconds, #fours;
    total_four_count +:= #fours;

    if #fours eq 0 then
        empty_four_descents +:= 1;
        printf "R20SEL|stage=four_descent|two_cover=%o|status=empty|action=do_not_interpret_as_rank_bound_without_review\\n",
            i;
        continue;
    end if;

    if #fours gt {four_cover_cap} then
        capped_four_descents +:= 1;
        printf "R20SEL|stage=four_descent|two_cover=%o|status=cap_exceeded|four_covers=%o|cap={four_cover_cap}\\n",
            i, #fours;
        continue;
    end if;

    for k in [1..#fours] do
        F := fours[k];
        printf "R20SEL|stage=four_cover|two_cover=%o|four=%o|equations=%o\\n",
            i, k, DefiningPolynomials(F);

        // Pair the 4-cover against all residual 2-covers before point search.
        p42 := [];
        obstructed := false;
        for j in [1..residual_count] do
            v := CasselsTatePairing(F, covers[j]);
            Append(~p42, v);
            if v ne 0 then
                obstructed := true;
            end if;
        end for;

        printf "R20SEL|stage=cassels_tate_4x2|two_cover=%o|four=%o|values=%o|obstructed=%o\\n",
            i, k, p42, obstructed;

        if obstructed then
            obstructed_four_count +:= 1;
            continue;
        end if;

        survivor_four_count +:= 1;

        printf "R20SEL|stage=points_qi|status=start|two_cover=%o|four=%o|bound={point_bound}\\n",
            i, k;
        search_start := Realtime();
        pts := PointsQI(F, {point_bound} : OnlyOne := true);
        search_seconds := Realtime(search_start);
        printf "R20SEL|stage=points_qi|status=complete|two_cover=%o|four=%o|seconds=%o|bound={point_bound}|points=%o\\n",
            i, k, search_seconds, #pts;

        if #pts gt 0 then
            _, toE := AssociatedEllipticCurve(F : E := E);
            P := toE(pts[1]);
            assert P in E;

            independent21, relation21 := IsLinearlyIndependent(known cat [P]);
            printf "R20SEL|stage=map_to_E|two_cover=%o|four=%o|point_QI=%o|point_E=%o|height=%o|independent21=%o|relation=%o\\n",
                i, k, pts[1], P, Height(P), independent21, relation21;

            candidate_count +:= 1;

            if independent21 then
                printf "R20SEL|classification=S3_RANK_AT_LEAST21_CANDIDATE|two_cover=%o|four=%o|point_E=%o\\n",
                    i, k, P;
            else
                printf "R20SEL|classification=S2_SATURATION_POINT|two_cover=%o|four=%o|point_E=%o|relation=%o|action=enlarge_rank20_lattice_and_rerun\\n",
                    i, k, P, relation21;
            end if;
        elif {eight} then
            // Run 8-descent only on a 4-cover that survived 4x2 pairing.
            printf "R20SEL|stage=eight_descent|status=start|two_cover=%o|four=%o\\n", i, k;
            eight_start := Realtime();
            eights, eight_maps := EightDescent(F);
            eight_seconds := Realtime(eight_start);
            printf "R20SEL|stage=eight_descent|status=complete|two_cover=%o|four=%o|seconds=%o|eight_covers=%o\\n",
                i, k, eight_seconds, #eights;
        end if;
    end for;
end for;

if candidate_count gt 0 then
    printf "R20SEL|stage=summary|residual_dim=%o|radical_dim=%o|total_four_covers=%o|obstructed_four_covers=%o|survivor_four_covers=%o|empty_four_descents=%o|capped_four_descents=%o|mapped_candidates=%o|action=inspect_S3_or_S2_records\\n",
        residual_dim, radical_dim, total_four_count, obstructed_four_count,
        survivor_four_count, empty_four_descents, capped_four_descents, candidate_count;
elif survivor_four_count gt 0 then
    printf "R20SEL|classification=S2_UNRESOLVED_HIGHER_DESCENT|residual_dim=%o|radical_dim=%o|total_four_covers=%o|obstructed_four_covers=%o|survivor_four_covers=%o|point_bound={point_bound}|action=raise_pointsqi_or_run_eight_descent\\n",
        residual_dim, radical_dim, total_four_count, obstructed_four_count,
        survivor_four_count;
elif empty_four_descents gt 0 or capped_four_descents gt 0 then
    printf "R20SEL|classification=S4_INCOMPLETE_HIGHER_DESCENT|residual_dim=%o|radical_dim=%o|empty_four_descents=%o|capped_four_descents=%o|action=review_or_rerun_before_any_rank_claim\\n",
        residual_dim, radical_dim, empty_four_descents, capped_four_descents;
else
    printf "R20SEL|classification=S1_HIGHER_CT_OBSTRUCTION|residual_dim=%o|radical_dim=%o|total_four_covers=%o|obstructed_four_covers=%o|survivor_four_covers=0|action=independent_review_before_promoting_exact_rank\\n",
        residual_dim, radical_dim, total_four_count, obstructed_four_count;
end if;
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path(
            "artifacts/generated-results/elliptic-curves/"
            "fermigier_rank20_near_miss_v1.json"
        ),
    )
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--point-bound",
        type=int,
        default=100_000,
        help="PointsQI bound on surviving 4-covers",
    )
    parser.add_argument(
        "--pairing-cover-cap",
        type=int,
        default=63,
        help="refuse an O(n^2) full pairing matrix above this many residual covers",
    )
    parser.add_argument(
        "--four-cover-cap",
        type=int,
        default=512,
        help="skip a 2-class if FourDescent returns more than this many 4-covers",
    )
    parser.add_argument(
        "--eight-descent",
        action="store_true",
        help="run EightDescent on 4-covers that survive 4x2 pairing and PointsQI",
    )
    args = parser.parse_args()

    if args.point_bound <= 0:
        raise ValueError("--point-bound must be positive")
    if args.pairing_cover_cap <= 0:
        raise ValueError("--pairing-cover-cap must be positive")
    if args.four_cover_cap <= 0:
        raise ValueError("--four-cover-cap must be positive")

    model, points = load_selected_points(args.manifest)
    if len(points) != KNOWN_RANK:
        raise ArithmeticError("expected exactly 20 pinned points")

    text = build_magma(
        model,
        points,
        point_bound=args.point_bound,
        pairing_cover_cap=args.pairing_cover_cap,
        four_cover_cap=args.four_cover_cap,
        run_eight_descent=args.eight_descent,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    print(f"WROTE {args.output}")
    print(f"POINT_BOUND={args.point_bound}")
    print(f"EIGHT_DESCENT={args.eight_descent}")
    print("PROTOCOL=R20SEL_v1")


if __name__ == "__main__":
    main()

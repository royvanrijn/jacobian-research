def on_curve(point: tuple[Q, Q]) -> bool:
    x_value, y_value = point
    return y_value * y_value + x_value * y_value == x_value**3 + A * x_value + B


def c4() -> int:
    return 1 - 48 * A


def c6() -> int:
    return -1 + 72 * A - 864 * B


def discriminant() -> int:
    return (c4() ** 3 - c6() ** 2) // 1728



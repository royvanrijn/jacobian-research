#!/usr/bin/env python3
"""Exact quotient-aware scoring for Mordell--Weil point searches.

Searches in this repository often find many rational points that ultimately
lie in the subgroup already generated by a pinned basis.  This module turns
the finite-reduction machinery used for final independence certificates into
an early search filter.

A block is a matrix whose columns are rational points and whose rows are exact
coordinates in a product of quotients ``E(F_p)/ell E(F_p)`` for one fixed
prime ``ell``.  If adding a candidate column increases the rank over
``F_ell``, its image is outside the image of the known subgroup.  In
particular, the point is not in the known subgroup.  Failure to escape at the
chosen finite quotients proves nothing: the reduction map may simply miss the
new direction.

The implementation is model-independent.  Existing mod-2, mod-3 and mod-5
certificate builders can feed their stored rows directly into this layer.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import isqrt
from typing import Iterable, Sequence


def _is_prime(value: int) -> bool:
    if value < 2:
        return False
    return all(value % divisor for divisor in range(2, isqrt(value) + 1))


def _normalize_rows(
    rows: Iterable[Sequence[int]], *, column_count: int, modulus: int
) -> tuple[tuple[int, ...], ...]:
    if not _is_prime(modulus):
        raise ValueError("the quotient modulus must be prime")
    normalized: list[tuple[int, ...]] = []
    for row in rows:
        current = tuple(int(value) % modulus for value in row)
        if len(current) != column_count:
            raise ValueError("every quotient row must have the declared width")
        normalized.append(current)
    return tuple(normalized)


def rank_mod_prime(
    rows: Iterable[Sequence[int]], *, column_count: int, modulus: int
) -> int:
    """Return the exact rank of a matrix over ``F_modulus``.

    Rows may be empty.  The declared column count is retained so that an empty
    quotient product has rank zero without losing its intended width.
    """

    matrix = [
        list(row)
        for row in _normalize_rows(
            rows, column_count=column_count, modulus=modulus
        )
    ]
    pivot_row = 0
    for column in range(column_count):
        pivot = next(
            (
                row_index
                for row_index in range(pivot_row, len(matrix))
                if matrix[row_index][column]
            ),
            None,
        )
        if pivot is None:
            continue
        matrix[pivot_row], matrix[pivot] = matrix[pivot], matrix[pivot_row]
        inverse = pow(matrix[pivot_row][column], -1, modulus)
        matrix[pivot_row] = [
            value * inverse % modulus for value in matrix[pivot_row]
        ]
        for row_index, row in enumerate(matrix):
            if row_index == pivot_row or not row[column]:
                continue
            factor = row[column]
            matrix[row_index] = [
                (left - factor * right) % modulus
                for left, right in zip(row, matrix[pivot_row], strict=True)
            ]
        pivot_row += 1
        if pivot_row == len(matrix):
            break
    return pivot_row


@dataclass(frozen=True)
class QuotientBlock:
    """One exact finite-quotient coordinate block.

    All blocks combined in one analysis must have the same modulus and point
    ordering.  ``source`` normally names a good reduction prime or a pinned
    certificate artifact.
    """

    modulus: int
    rows: tuple[tuple[int, ...], ...]
    source: str

    @classmethod
    def build(
        cls,
        *,
        modulus: int,
        rows: Iterable[Sequence[int]],
        column_count: int,
        source: str,
    ) -> "QuotientBlock":
        if not source:
            raise ValueError("a quotient block needs a nonempty source label")
        return cls(
            modulus=modulus,
            rows=_normalize_rows(
                rows, column_count=column_count, modulus=modulus
            ),
            source=source,
        )


@dataclass(frozen=True)
class EscapeProfile:
    modulus: int
    known_column_count: int
    candidate_labels: tuple[str, ...]
    source_labels: tuple[str, ...]
    baseline_rank: int
    combined_rank: int
    marginal_dimension: int
    individually_escaping_labels: tuple[str, ...]
    independent_escape_basis_labels: tuple[str, ...]

    @property
    def any_escape(self) -> bool:
        return self.marginal_dimension > 0

    def to_record(self) -> dict[str, object]:
        return {
            "modulus": self.modulus,
            "known_column_count": self.known_column_count,
            "candidate_labels": list(self.candidate_labels),
            "source_labels": list(self.source_labels),
            "baseline_rank": self.baseline_rank,
            "combined_rank": self.combined_rank,
            "marginal_dimension": self.marginal_dimension,
            "individually_escaping_labels": list(
                self.individually_escaping_labels
            ),
            "independent_escape_basis_labels": list(
                self.independent_escape_basis_labels
            ),
            "claim_boundary": (
                "escape proves the point image is outside the known subgroup "
                "image; non-escape is not a dependence proof"
            ),
        }


def analyze_escape(
    blocks: Sequence[QuotientBlock],
    *,
    known_column_count: int,
    candidate_labels: Sequence[str],
) -> EscapeProfile:
    """Measure candidate directions beyond a known subgroup image.

    ``candidate_labels`` determines the columns after the known prefix.  The
    independent escape basis is selected deterministically in that order.
    Individual escape is tested against the unchanged known prefix and is
    therefore independent of candidate ordering.
    """

    if not blocks:
        raise ValueError("at least one quotient block is required")
    if known_column_count < 0:
        raise ValueError("known_column_count must be nonnegative")
    labels = tuple(str(label) for label in candidate_labels)
    if any(not label for label in labels) or len(set(labels)) != len(labels):
        raise ValueError("candidate labels must be nonempty and distinct")
    total_columns = known_column_count + len(labels)
    modulus = blocks[0].modulus
    if any(block.modulus != modulus for block in blocks):
        raise ValueError("all quotient blocks in one profile need one modulus")
    if any(any(len(row) != total_columns for row in block.rows) for block in blocks):
        raise ValueError("quotient block width does not match the point inventory")

    rows = tuple(row for block in blocks for row in block.rows)

    def restricted_rank(columns: Sequence[int]) -> int:
        restricted = tuple(
            tuple(row[column] for column in columns) for row in rows
        )
        return rank_mod_prime(
            restricted, column_count=len(columns), modulus=modulus
        )

    known_columns = tuple(range(known_column_count))
    baseline_rank = restricted_rank(known_columns)
    all_columns = tuple(range(total_columns))
    combined_rank = restricted_rank(all_columns)

    individually_escaping: list[str] = []
    for offset, label in enumerate(labels):
        candidate_column = known_column_count + offset
        if restricted_rank((*known_columns, candidate_column)) > baseline_rank:
            individually_escaping.append(label)

    selected_columns = list(known_columns)
    current_rank = baseline_rank
    escape_basis: list[str] = []
    for offset, label in enumerate(labels):
        candidate_column = known_column_count + offset
        proposed = (*selected_columns, candidate_column)
        proposed_rank = restricted_rank(proposed)
        if proposed_rank > current_rank:
            selected_columns.append(candidate_column)
            current_rank = proposed_rank
            escape_basis.append(label)

    if current_rank != combined_rank:
        raise AssertionError("greedy column selection missed the exact rank")
    return EscapeProfile(
        modulus=modulus,
        known_column_count=known_column_count,
        candidate_labels=labels,
        source_labels=tuple(block.source for block in blocks),
        baseline_rank=baseline_rank,
        combined_rank=combined_rank,
        marginal_dimension=combined_rank - baseline_rank,
        individually_escaping_labels=tuple(individually_escaping),
        independent_escape_basis_labels=tuple(escape_basis),
    )


@dataclass(frozen=True)
class MultiModulusEscapeProfile:
    profiles: tuple[EscapeProfile, ...]

    @property
    def moduli_with_escape(self) -> tuple[int, ...]:
        return tuple(profile.modulus for profile in self.profiles if profile.any_escape)

    @property
    def maximum_marginal_dimension(self) -> int:
        return max((profile.marginal_dimension for profile in self.profiles), default=0)

    @property
    def aggregate_priority_key(self) -> tuple[int, int, int]:
        """A deterministic search-order key, not a probability or rank bound."""

        return (
            len(self.moduli_with_escape),
            self.maximum_marginal_dimension,
            sum(profile.marginal_dimension for profile in self.profiles),
        )

    def to_record(self) -> dict[str, object]:
        return {
            "profiles": [profile.to_record() for profile in self.profiles],
            "moduli_with_escape": list(self.moduli_with_escape),
            "maximum_marginal_dimension": self.maximum_marginal_dimension,
            "aggregate_priority_key": list(self.aggregate_priority_key),
            "claim_boundary": (
                "the priority key ranks exact quotient evidence only; it is "
                "not a calibrated rank probability"
            ),
        }


def analyze_multi_modulus_escape(
    blocks: Sequence[QuotientBlock],
    *,
    known_column_count: int,
    candidate_labels: Sequence[str],
) -> MultiModulusEscapeProfile:
    if not blocks:
        raise ValueError("at least one quotient block is required")
    grouped: dict[int, list[QuotientBlock]] = {}
    for block in blocks:
        grouped.setdefault(block.modulus, []).append(block)
    profiles = tuple(
        analyze_escape(
            grouped[modulus],
            known_column_count=known_column_count,
            candidate_labels=candidate_labels,
        )
        for modulus in sorted(grouped)
    )
    return MultiModulusEscapeProfile(profiles)

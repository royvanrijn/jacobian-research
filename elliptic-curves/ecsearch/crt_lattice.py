"""Exact one-parameter Hensel, CRT, and Gauss-lattice primitives.

The central congruence is

    a - r*b == 0 (mod M),

whose integer solutions form the rank-two lattice generated by ``(M, 0)``
and ``(r, 1)``.  In dimension two, exact Gauss reduction is sufficient; no
floating-point LLL implementation is needed.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import product
from math import gcd
from typing import Iterable, Sequence


Vector = tuple[int, int]


@dataclass(frozen=True)
class RationalRepresentative:
    """A primitive rational representative of a congruence class."""

    numerator: int
    denominator: int
    weighted_norm: int

    @property
    def height(self) -> int:
        return max(abs(self.numerator), self.denominator)


def evaluate_polynomial(
    coefficients: Sequence[int], value: int, modulus: int | None = None
) -> int:
    """Evaluate low-to-high integer coefficients, optionally modulo ``modulus``."""

    if not coefficients:
        raise ValueError("a polynomial needs at least one coefficient")
    if modulus is not None and modulus <= 0:
        raise ValueError("modulus must be positive")
    result = 0
    for coefficient in reversed(coefficients):
        result = result * value + coefficient
        if modulus is not None:
            result %= modulus
    return result


def roots_mod_prime(coefficients: Sequence[int], prime: int) -> list[int]:
    """Return every root modulo a (caller-supplied) prime."""

    if prime < 2:
        raise ValueError("prime must be at least two")
    return [
        residue
        for residue in range(prime)
        if evaluate_polynomial(coefficients, residue, prime) == 0
    ]


def hensel_lift_roots(
    coefficients: Sequence[int],
    prime: int,
    exponent: int,
    *,
    maximum_roots: int | None = None,
) -> list[int]:
    """Return all roots modulo ``prime**exponent``.

    Each root modulo ``p**e`` is tested against all of its ``p`` lifts.  This
    deliberately handles singular roots too; it is slower than simple-root
    Newton lifting but exact and adequate for the small local tables used at
    the constraint-selection stage.
    """

    if exponent < 1:
        raise ValueError("exponent must be positive")
    if maximum_roots is not None and maximum_roots < 1:
        raise ValueError("maximum_roots must be positive or None")
    roots = roots_mod_prime(coefficients, prime)
    if maximum_roots is not None and len(roots) > maximum_roots:
        raise ValueError(
            f"more than {maximum_roots} roots occur modulo {prime}"
        )
    modulus = prime
    for reached_exponent in range(2, exponent + 1):
        next_modulus = modulus * prime
        next_roots = []
        for root in roots:
            for digit in range(prime):
                candidate = root + digit * modulus
                if (
                    evaluate_polynomial(coefficients, candidate, next_modulus)
                    != 0
                ):
                    continue
                next_roots.append(candidate)
                if (
                    maximum_roots is not None
                    and len(next_roots) > maximum_roots
                ):
                    raise ValueError(
                        f"more than {maximum_roots} roots occur modulo "
                        f"{prime}^{reached_exponent}"
                    )
        roots = next_roots
        modulus = next_modulus
    return sorted(roots)


def crt(congruences: Iterable[tuple[int, int]]) -> tuple[int, int]:
    """Combine compatible congruences as ``(residue, modulus)``.

    The generalized form is used so constraints involving the same prime can
    later be intersected safely.  Incompatible congruences raise ``ValueError``.
    """

    residue = 0
    modulus = 1
    seen = False
    for next_residue, next_modulus in congruences:
        seen = True
        if next_modulus <= 0:
            raise ValueError("CRT moduli must be positive")
        next_residue %= next_modulus
        common = gcd(modulus, next_modulus)
        difference = next_residue - residue
        if difference % common:
            raise ValueError("CRT congruences are incompatible")
        old_reduced = modulus // common
        next_reduced = next_modulus // common
        if next_reduced == 1:
            multiplier = 0
        else:
            multiplier = (
                (difference // common)
                * pow(old_reduced, -1, next_reduced)
            ) % next_reduced
        residue += modulus * multiplier
        modulus *= next_reduced
        residue %= modulus
    if not seen:
        raise ValueError("at least one congruence is required")
    return residue, modulus


def _nearest_integer(numerator: int, denominator: int) -> int:
    """Round an exact ratio to nearest, resolving ties toward an even integer."""

    if denominator <= 0:
        raise ValueError("denominator must be positive")
    quotient, remainder = divmod(numerator, denominator)
    comparison = 2 * remainder - denominator
    if comparison < 0:
        return quotient
    if comparison > 0:
        return quotient + 1
    return quotient if quotient % 2 == 0 else quotient + 1


def _inner(left: Vector, right: Vector, weights: Vector) -> int:
    return (
        weights[0] * left[0] * right[0]
        + weights[1] * left[1] * right[1]
    )


def gauss_reduce_lattice_basis(
    first: Vector, second: Vector, *, weights: Vector = (1, 1)
) -> tuple[Vector, Vector]:
    """Gauss-reduce an arbitrary rank-two integral lattice exactly."""

    if first[0] * second[1] - first[1] * second[0] == 0:
        raise ValueError("the lattice basis must have rank two")
    if len(weights) != 2 or any(
        type(weight) is not int or weight <= 0 for weight in weights
    ):
        raise ValueError("weights must be exactly two positive integers")
    while True:
        if _inner(second, second, weights) < _inner(first, first, weights):
            first, second = second, first
        multiplier = _nearest_integer(
            _inner(first, second, weights), _inner(first, first, weights)
        )
        if multiplier == 0:
            return first, second
        second = (
            second[0] - multiplier * first[0],
            second[1] - multiplier * first[1],
        )


def gauss_reduce_congruence_lattice(
    residue: int, modulus: int, *, weights: Vector = (1, 1)
) -> tuple[Vector, Vector]:
    """Gauss-reduce the lattice ``a == residue*b (mod modulus)`` exactly."""

    if modulus <= 0:
        raise ValueError("modulus must be positive")
    residue %= modulus
    first, second = gauss_reduce_lattice_basis(
        (modulus, 0), (residue, 1), weights=weights
    )
    assert abs(first[0] * second[1] - first[1] * second[0]) == modulus
    assert (first[0] - residue * first[1]) % modulus == 0
    assert (second[0] - residue * second[1]) % modulus == 0
    return first, second


def gauss_reduce_linear_congruence_lattice(
    coefficient_a: int,
    coefficient_b: int,
    modulus: int,
    *,
    weights: Vector = (1, 1),
) -> tuple[Vector, Vector]:
    """Reduce the kernel of ``C*a + D*b == 0 (mod M)``.

    The row must be primitive modulo ``M``.  This form supports mixtures of
    the affine chart ``a-r*b=0`` and the infinity chart ``b-s*a=0``.
    """

    if modulus <= 0:
        raise ValueError("modulus must be positive")
    divisor = gcd(coefficient_a, modulus)
    if gcd(divisor, coefficient_b) != 1:
        raise ValueError("the congruence row must be primitive modulo M")
    quotient = modulus // divisor
    residue = 0
    if quotient > 1:
        residue = (
            -coefficient_b
            * pow(coefficient_a // divisor, -1, quotient)
        ) % quotient
    first, second = gauss_reduce_lattice_basis(
        (quotient, 0), (residue, divisor), weights=weights
    )
    determinant = abs(first[0] * second[1] - first[1] * second[0])
    if determinant != modulus:
        raise AssertionError("the reduced kernel has the wrong determinant")
    for numerator, denominator in (first, second):
        if (
            coefficient_a * numerator + coefficient_b * denominator
        ) % modulus:
            raise AssertionError("a reduced basis vector left the kernel")
    return first, second


def _normalize_rational(vector: Vector) -> Vector:
    numerator, denominator = vector
    common = gcd(abs(numerator), abs(denominator))
    if common:
        numerator //= common
        denominator //= common
    if denominator < 0:
        numerator = -numerator
        denominator = -denominator
    return numerator, denominator


def enumerate_rational_representatives(
    residue: int,
    modulus: int,
    *,
    coefficient_radius: int = 4,
    weights: Vector = (1, 1),
) -> list[RationalRepresentative]:
    """Enumerate a bounded neighbourhood of a reduced congruence basis.

    The enumeration is a bounded search in reduced-basis coordinates, not a
    proof that the returned first element is the globally shortest admissible
    primitive pair.  A pair is admissible only if its denominator is invertible
    modulo ``M``.  This check is essential: dividing a shortest imprimitive
    vector can otherwise destroy the original congruence.
    """

    if coefficient_radius < 1:
        raise ValueError("coefficient_radius must be positive")
    first, second = gauss_reduce_congruence_lattice(
        residue, modulus, weights=weights
    )
    representatives: dict[Vector, RationalRepresentative] = {}
    coefficient_range = range(-coefficient_radius, coefficient_radius + 1)
    for first_coefficient, second_coefficient in product(
        coefficient_range, repeat=2
    ):
        if first_coefficient == 0 and second_coefficient == 0:
            continue
        vector = (
            first_coefficient * first[0] + second_coefficient * second[0],
            first_coefficient * first[1] + second_coefficient * second[1],
        )
        numerator, denominator = _normalize_rational(vector)
        if denominator == 0 or gcd(denominator, modulus) != 1:
            continue
        if (numerator - residue * denominator) % modulus != 0:
            continue
        weighted_norm = (
            weights[0] * numerator * numerator
            + weights[1] * denominator * denominator
        )
        representative = RationalRepresentative(
            numerator=numerator,
            denominator=denominator,
            weighted_norm=weighted_norm,
        )
        previous = representatives.get((numerator, denominator))
        if previous is None or representative.weighted_norm < previous.weighted_norm:
            representatives[(numerator, denominator)] = representative
    return sorted(
        representatives.values(),
        key=lambda item: (
            item.weighted_norm,
            item.height,
            abs(item.numerator),
            item.denominator,
            item.numerator,
        ),
    )


def enumerate_rationals_in_height_box(
    residue: int,
    modulus: int,
    *,
    numerator_bound: int,
    denominator_bound: int,
    weights: Vector = (1, 1),
) -> list[RationalRepresentative]:
    """Exhaust every admissible rational in a rectangular height box.

    Unlike ``enumerate_rational_representatives``, this is a complete finite
    enumeration.  Bounds on reduced-basis coefficients follow by applying the
    inverse two-by-two basis matrix to every vector with
    ``|a| <= numerator_bound`` and ``|b| <= denominator_bound``.
    """

    if numerator_bound < 0 or denominator_bound < 1:
        raise ValueError("height-box bounds must be nonnegative, with b-bound positive")
    first, second = gauss_reduce_congruence_lattice(
        residue, modulus, weights=weights
    )
    determinant = first[0] * second[1] - first[1] * second[0]
    determinant_abs = abs(determinant)
    first_coefficient_bound = (
        abs(second[1]) * numerator_bound
        + abs(second[0]) * denominator_bound
    ) // determinant_abs
    second_coefficient_bound = (
        abs(first[1]) * numerator_bound
        + abs(first[0]) * denominator_bound
    ) // determinant_abs
    representatives: dict[Vector, RationalRepresentative] = {}
    for first_coefficient in range(
        -first_coefficient_bound, first_coefficient_bound + 1
    ):
        for second_coefficient in range(
            -second_coefficient_bound, second_coefficient_bound + 1
        ):
            if first_coefficient == 0 and second_coefficient == 0:
                continue
            vector = (
                first_coefficient * first[0] + second_coefficient * second[0],
                first_coefficient * first[1] + second_coefficient * second[1],
            )
            if (
                abs(vector[0]) > numerator_bound
                or abs(vector[1]) > denominator_bound
            ):
                continue
            numerator, denominator = _normalize_rational(vector)
            if (
                denominator == 0
                or abs(numerator) > numerator_bound
                or denominator > denominator_bound
                or gcd(denominator, modulus) != 1
                or (numerator - residue * denominator) % modulus != 0
            ):
                continue
            representative = RationalRepresentative(
                numerator=numerator,
                denominator=denominator,
                weighted_norm=(
                    weights[0] * numerator * numerator
                    + weights[1] * denominator * denominator
                ),
            )
            representatives[(numerator, denominator)] = representative
    return sorted(
        representatives.values(),
        key=lambda item: (
            item.height,
            item.weighted_norm,
            abs(item.numerator),
            item.denominator,
            item.numerator,
        ),
    )


def first_rationals_by_height(
    residue: int,
    modulus: int,
    *,
    count: int = 1,
    maximum_height: int,
    weights: Vector = (1, 1),
) -> tuple[list[RationalRepresentative], int]:
    """Find the first ``count`` admissible rationals by exhaustive doubling.

    The returned second value is the final exhaustively checked height.  If no
    sufficient list exists through ``maximum_height``, ``ValueError`` is raised.
    """

    if count < 1 or maximum_height < 1:
        raise ValueError("count and maximum_height must be positive")
    height = 1
    while True:
        checked_height = min(height, maximum_height)
        representatives = enumerate_rationals_in_height_box(
            residue,
            modulus,
            numerator_bound=checked_height,
            denominator_bound=checked_height,
            weights=weights,
        )
        if len(representatives) >= count:
            return representatives[:count], checked_height
        if checked_height == maximum_height:
            raise ValueError(
                f"fewer than {count} admissible rationals through height "
                f"{maximum_height}"
            )
        height *= 2


def p_adic_valuation(value: int, prime: int) -> int:
    """Return ``v_prime(value)`` for a nonzero integer."""

    if value == 0:
        raise ValueError("the valuation of zero is not finite")
    if prime < 2:
        raise ValueError("prime must be at least two")
    value = abs(value)
    valuation = 0
    while value % prime == 0:
        value //= prime
        valuation += 1
    return valuation

"""Build quotient-first rank-jump fingerprints for the four R17 controls.

The output concerns the certified subgroup generated by each public point
list.  It does not assume that this subgroup is the full Mordell--Weil group.
For a specialized generic subgroup ``M`` inside a displayed subgroup ``L`` it
records

* the exact Smith structure of ``L/M``;
* its exact dimensions after tensoring with F_2, F_3, and F_5;
* the canonical-height quotient lattice obtained by orthogonal projection
  away from ``M_R``;
* complete degree-two bisection visibility as a binary quotient-code matroid.

The quotient heights are numerical canonical heights at the declared PARI
precision.  The Smith, finite-code, and cover-square calculations are exact.
"""


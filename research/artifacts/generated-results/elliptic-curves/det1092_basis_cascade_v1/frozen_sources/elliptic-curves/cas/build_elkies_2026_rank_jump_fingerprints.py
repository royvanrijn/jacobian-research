def build_fingerprint(
    truth: dict[str, object],
    control: dict[str, object],
    bisection: dict[str, object],
    *,
    digits: int,
    maximum_vectors: int,
    shortest_vector_count: int,
    timeout: float,
) -> dict[str, object]:
    if not (truth["label"] == control["label"] == bisection["label"]):
        raise ValueError("control labels do not align")
    if not (truth["parameter"] == control["parameter"] == bisection["parameter"]):
        raise ValueError("control parameters do not align")
    rank = int(control["published_rank_lower_bound"])
    module = importlib.import_module(f"elkies_rank{rank}")
    curve = EllipticCurve(module.GENERAL_WEIERSTRASS_COEFFICIENTS)
    public_points = tuple(module.POINTS)
    if len(public_points) != rank:
        raise ArithmeticError("public point count and advertised rank differ")
    gram = height_gram(curve, public_points, digits=digits, timeout=timeout)
    smith = smith_quotient_record(
        ambient_rank=rank,
        subgroup_rank=int(truth["truth_rank"]),
        smith_factors=truth["smith_invariant_factors"],
    )
    geometry = quotient_height_geometry(
        gram,
        truth["embedding_matrix_columns"],
        digits=digits,
        maximum_vectors=maximum_vectors,
        shortest_vector_count=shortest_vector_count,
        timeout=timeout,
    )
    return {
        "label": control["label"],
        "parameter": control["parameter"],
        "global_minimal_model": control["minimal_model"],
        "certified_rank_lower_bound": rank,
        "generic_rank": int(truth["truth_rank"]),
        "quotient_structure": smith,
        "quotient_height_geometry": geometry,
        "degree_visibility": degree_visibility_ledger(bisection),
        "response_variables": {
            "primary_lower_bound": smith["free_quotient_rank_lower_bound"],
            "prime_local_dimensions": smith["tensor_dimensions_over_f_ell"],
            "degree_two_visible_dimension_over_f2": bisection["split_class_span"],
        },
    }


def build_mechanism_fingerprint(
    certificate: dict[str, object],
    bisection: dict[str, object],
    *,
    digits: int,
    maximum_vectors: int,
    shortest_vector_count: int,
    timeout: float,
) -> dict[str, object]:
    """Build the lower-jump t=3/8 control from its certified mixed basis."""

    if not (certificate["parameter"] == bisection["parameter"] == "3/8"):
        raise ValueError("the mechanism-control parameter changed")
    rank_record = certificate["rank_lower_bound"]
    rank = int(rank_record["certified_rank"])
    generic_rank = int(certificate["compact_specialization"]["generic_section_count"])
    points = tuple(
        tuple(Fraction(value) for value in point)
        for point in rank_record["combined_points"]
    )
    model = tuple(Fraction(value) for value in certificate["curve"]["global_minimal_model"])
    if len(points) != rank or generic_rank != 17 or rank != 21:
        raise ArithmeticError("the t=3/8 certified basis changed")
    embedding = tuple(
        tuple(int(row == column) for row in range(rank))
        for column in range(generic_rank)
    )
    curve = EllipticCurve(model)
    gram = height_gram(curve, points, digits=digits, timeout=timeout)
    smith = smith_quotient_record(
        ambient_rank=rank,
        subgroup_rank=generic_rank,
        smith_factors=(1,) * generic_rank,
    )
    geometry = quotient_height_geometry(
        gram,
        embedding,
        digits=digits,
        maximum_vectors=maximum_vectors,
        shortest_vector_count=shortest_vector_count,
        timeout=timeout,
    )
    visibility = degree_visibility_ledger(bisection)
    return {
        "label": bisection["label"],
        "parameter": "3/8",
        "global_minimal_model": [str(value) for value in model],
        "certified_rank_lower_bound": rank,
        "generic_rank": generic_rank,
        "control_role": (
            "lower-jump mechanism control; added after the four published high-rank "
            "controls and not used to retune their feature construction"
        ),
        "quotient_structure": smith,
        "quotient_height_geometry": geometry,
        "degree_visibility": visibility,
        "response_variables": {
            "primary_lower_bound": smith["free_quotient_rank_lower_bound"],
            "prime_local_dimensions": smith["tensor_dimensions_over_f_ell"],
            "degree_two_visible_dimension_over_f2": visibility[0][
                "visible_exceptional_span_dimension_over_f2"
            ],
        },
    }



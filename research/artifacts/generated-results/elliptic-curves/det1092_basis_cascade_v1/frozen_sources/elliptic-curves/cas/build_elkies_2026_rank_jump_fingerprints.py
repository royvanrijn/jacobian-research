    control_document = json.loads(args.controls.read_text())
    bisection_document = json.loads(args.bisection_controls.read_text())
    mechanism_document = json.loads(MECHANISM_CONTROL.read_text())
    truths = {row["label"]: row for row in truth_document["positive_controls"]}
    bisections = {row["label"]: row for row in bisection_document["fibres"]}

#!/usr/bin/env python3
"""Generate a source-pinned Magma 2-Selmer job for one near miss.

The cheaper ``selmer-dimension`` mode calls ``TwoSelmerGroup`` without
constructing covers.  Since the manifest certifies the full dimension of the
known Kummer image and trivial rational 2-torsion, subtracting that dimension
gives the exact residual quotient dimension.  The ``relative-covers`` mode
then calls ``TwoDescent`` with ``RemoveGens`` equal to that exact subgroup and
prints nonzero covers and their Cassels--Tate pairing.  The independent
``three-selmer-dimension`` mode can close a rank gap without constructing
3-covers.  No GRH class-group bounds are enabled.
"""

from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MANIFEST = (
    ROOT
    / "artifacts/generated-results/elliptic-curves/"
    "conductor_first_near_miss_descent_targets_v1.json"
)
EXPECTED_SCHEMA = "elliptic-curves.conductor-first-near-miss-descent-targets.v1"
PILOT_SCHEMA = "elliptic-curves.conductor-first-family-anchor-pilot.v1"


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def magma_q(value: str | int) -> str:
    value = Fraction(value)
    return f"({value.numerator}/{value.denominator})"


def load_target(path: Path, target_id: str) -> tuple[dict[str, Any], dict[str, Any]]:
    manifest = json.loads(path.read_text())
    schema = manifest.get("schema")
    if schema == EXPECTED_SCHEMA:
        candidates = manifest["targets"]
    elif schema == PILOT_SCHEMA:
        candidates = []
        for record in manifest["candidates"]:
            subgroup = record.get("known_subgroup")
            if subgroup is None:
                continue
            candidates.append(
                {
                    "id": record["id"],
                    "descent_model": record["source_model"],
                    "known_basis": subgroup["known_basis"],
                    "certified_known_rank": subgroup[
                        "certified_rank_lower_bound"
                    ],
                    "known_kummer_image_dimension": subgroup[
                        "kummer_image_dimension"
                    ],
                    "rational_two_torsion_dimension": subgroup[
                        "rational_two_torsion_dimension"
                    ],
                }
            )
    else:
        raise ValueError("input is not a supported conductor-first manifest")
    matches = [target for target in candidates if target["id"] == target_id]
    if len(matches) != 1:
        available = ", ".join(target["id"] for target in candidates)
        raise ValueError(f"unknown target {target_id}; choose one of {available}")
    target = matches[0]
    if target["known_kummer_image_dimension"] != target["certified_known_rank"]:
        raise ArithmeticError("target subgroup is not certified full-dimensional mod 2")
    if target["rational_two_torsion_dimension"] != 0:
        raise ArithmeticError("this job expects trivial rational 2-torsion")
    return manifest, target


def build_magma(
    target: dict[str, Any], *, manifest_sha256: str, pairing_cover_cap: int
) -> str:
    target_id = target["id"]
    known_rank = int(target["certified_known_rank"])
    model = ", ".join(magma_q(value) for value in target["descent_model"])
    points = ",\n    ".join(
        f"E![{magma_q(point[0])}, {magma_q(point[1])}, 1]"
        for point in target["known_basis"]
    )
    return f'''// Generated by build_conductor_first_near_miss_magma.py
// Protocol CFNMSEL v1. No SetClassGroupBounds("GRH") is used.
// Target manifest SHA-256: {manifest_sha256}

Q := Rationals();
E := EllipticCurve([{model}]);
known := [
    {points}
];

function ExactLog2(n)
    assert n ge 1;
    d := 0;
    m := 1;
    while m lt n do
        m *:= 2;
        d +:= 1;
    end while;
    assert m eq n;
    return d;
end function;

printf "CFNMSEL|version=1|target={target_id}|stage=input|magma=%o|known=%o|manifest_sha256={manifest_sha256}\\n",
    GetVersion(), #known;
assert #known eq {known_rank};
assert &and[P in E : P in known];

T2, T2map := TwoTorsionSubgroup(E);
t2dim := ExactLog2(#T2);
printf "CFNMSEL|target={target_id}|stage=torsion|order=%o|dimension=%o\\n", #T2, t2dim;
assert t2dim eq 0;

printf "CFNMSEL|target={target_id}|stage=two_descent|status=start\\n";
started := Realtime();
covers, maps, quotient_map := TwoDescent(
    E :
    RemoveGens := SequenceToSet(known),
    RemoveTorsion := true
);
seconds := Realtime(started);
residual_count := #covers;
residual_dim := ExactLog2(residual_count + 1);
selmer_dim := {known_rank} + residual_dim;
printf "CFNMSEL|target={target_id}|stage=two_descent|status=complete|seconds=%o|residual_nonzero_classes=%o|residual_dim=%o|selmer_dim=%o\\n",
    seconds, residual_count, residual_dim, selmer_dim;

for i in [1..#covers] do
    f, h := HyperellipticPolynomials(covers[i]);
    printf "CFNMSEL|target={target_id}|stage=two_cover|index=%o|f=%o|h=%o\\n", i, f, h;
end for;

if residual_count eq 0 then
    printf "CFNMSEL|target={target_id}|classification=CLOSED_EXACT_RANK_{known_rank}|rank_lower={known_rank}|rank_upper={known_rank}|reason=zero_residual_2_selmer\\n";
    quit;
end if;

if residual_count gt {pairing_cover_cap} then
    printf "CFNMSEL|target={target_id}|classification=RESIDUAL_COVERS_UNPAIRED|residual_dim=%o|nonzero_classes=%o|pairing_cap={pairing_cover_cap}\\n",
        residual_dim, residual_count;
    quit;
end if;

printf "CFNMSEL|target={target_id}|stage=cassels_tate|status=start|classes=%o\\n", residual_count;
pair_started := Realtime();
M := ZeroMatrix(Integers(), residual_count, residual_count);
for i in [1..residual_count] do
    for j in [i+1..residual_count] do
        value := CasselsTatePairing(covers[i], covers[j]);
        M[i,j] := value;
        M[j,i] := value;
        printf "CFNMSEL|target={target_id}|stage=cassels_tate_entry|i=%o|j=%o|value=%o\\n",
            i, j, value;
    end for;
end for;
pair_seconds := Realtime(pair_started);
radical := [
    i : i in [1..residual_count] |
    &and[M[i,j] eq 0 : j in [1..residual_count]]
];
radical_dim := ExactLog2(#radical + 1);
rank_upper_after_pairing := {known_rank} + radical_dim;
printf "CFNMSEL|target={target_id}|stage=cassels_tate|status=complete|seconds=%o|matrix=%o|radical_indices=%o|radical_dim=%o|rank_upper_after_pairing=%o\\n",
    pair_seconds, Eltseq(M), radical, radical_dim, rank_upper_after_pairing;

if radical_dim eq 0 then
    printf "CFNMSEL|target={target_id}|classification=CLOSED_EXACT_RANK_{known_rank}_CT|rank_lower={known_rank}|rank_upper={known_rank}|reason=zero_residual_pairing_radical\\n";
else
    printf "CFNMSEL|target={target_id}|classification=HIGHER_DESCENT_REQUIRED|residual_dim=%o|radical_dim=%o|radical_indices=%o|action=four_descent_only_on_radical_classes\\n",
        residual_dim, radical_dim, radical;
end if;
'''


def build_selmer_dimension_magma(
    target: dict[str, Any], *, manifest_sha256: str
) -> str:
    target_id = target["id"]
    known_rank = int(target["certified_known_rank"])
    model = ", ".join(magma_q(value) for value in target["descent_model"])
    return f'''// Generated by build_conductor_first_near_miss_magma.py
// Protocol CFNMSEL v1, dimension-only first pass.
// No SetClassGroupBounds("GRH") is used.
// Target manifest SHA-256: {manifest_sha256}

Q := Rationals();
E := EllipticCurve([{model}]);

function ExactLog2(n)
    assert n ge 1;
    d := 0;
    m := 1;
    while m lt n do
        m *:= 2;
        d +:= 1;
    end while;
    assert m eq n;
    return d;
end function;

printf "CFNMSEL|version=1|target={target_id}|stage=input|mode=selmer_dimension|magma=%o|known_kummer_dim={known_rank}|manifest_sha256={manifest_sha256}\\n",
    GetVersion();

T2, T2map := TwoTorsionSubgroup(E);
t2dim := ExactLog2(#T2);
printf "CFNMSEL|target={target_id}|stage=torsion|order=%o|dimension=%o\\n", #T2, t2dim;
assert t2dim eq 0;

printf "CFNMSEL|target={target_id}|stage=two_selmer_group|status=start\\n";
started := Realtime();
S, AtoS := TwoSelmerGroup(E);
seconds := Realtime(started);
assert &and[n eq 2 : n in Invariants(S)];
selmer_dim := Ngens(S);
assert selmer_dim ge {known_rank};
residual_dim := selmer_dim - {known_rank};
printf "CFNMSEL|target={target_id}|stage=two_selmer_group|status=complete|seconds=%o|selmer_order=%o|selmer_dim=%o|known_kummer_dim={known_rank}|residual_dim=%o\\n",
    seconds, #S, selmer_dim, residual_dim;

if residual_dim eq 0 then
    printf "CFNMSEL|target={target_id}|classification=CLOSED_EXACT_RANK_{known_rank}|rank_lower={known_rank}|rank_upper={known_rank}|reason=zero_residual_2_selmer\\n";
else
    printf "CFNMSEL|target={target_id}|classification=RESIDUAL_COVERS_REQUIRED|rank_lower={known_rank}|rank_upper=%o|residual_dim=%o|action=relative_two_descent\\n",
        selmer_dim, residual_dim;
end if;
'''


def build_three_selmer_dimension_magma(
    target: dict[str, Any], *, manifest_sha256: str
) -> str:
    target_id = target["id"]
    known_rank = int(target["certified_known_rank"])
    model = ", ".join(magma_q(value) for value in target["descent_model"])
    return f'''// Generated by build_conductor_first_near_miss_magma.py
// Protocol CFNMSEL v1, independent 3-Selmer dimension pass.
// No SetClassGroupBounds("GRH") is used.
// Target manifest SHA-256: {manifest_sha256}

Q := Rationals();
E := EllipticCurve([{model}]);

function ExactLog3(n)
    assert n ge 1;
    d := 0;
    m := 1;
    while m lt n do
        m *:= 3;
        d +:= 1;
    end while;
    assert m eq n;
    return d;
end function;

printf "CFNMSEL|version=1|target={target_id}|stage=input|mode=three_selmer_dimension|magma=%o|known_rank={known_rank}|manifest_sha256={manifest_sha256}\\n",
    GetVersion();

T3power, T3map := pPowerTorsion(E, 3);
t3order := #[g : g in T3power | 3*g eq T3power!0];
t3dim := ExactLog3(t3order);
printf "CFNMSEL|target={target_id}|stage=three_torsion|order=%o|dimension=%o|three_power_torsion_order=%o\\n",
    t3order, t3dim, #T3power;

printf "CFNMSEL|target={target_id}|stage=three_selmer_group|status=start\\n";
started := Realtime();
S3, S3toA := ThreeSelmerGroup(E);
seconds := Realtime(started);
assert &and[n eq 3 : n in Invariants(S3)];
selmer_dim := Ngens(S3);
rank_upper := selmer_dim - t3dim;
assert rank_upper ge {known_rank};
residual_rank_gap := rank_upper - {known_rank};
printf "CFNMSEL|target={target_id}|stage=three_selmer_group|status=complete|seconds=%o|selmer_order=%o|selmer_dim=%o|three_torsion_dim=%o|rank_upper=%o|known_rank={known_rank}|residual_rank_gap=%o\\n",
    seconds, #S3, selmer_dim, t3dim, rank_upper, residual_rank_gap;

if residual_rank_gap eq 0 then
    printf "CFNMSEL|target={target_id}|classification=CLOSED_EXACT_RANK_{known_rank}_BY_3_SELMER|rank_lower={known_rank}|rank_upper={known_rank}|reason=matching_three_selmer_bound\\n";
else
    printf "CFNMSEL|target={target_id}|classification=THREE_SELMER_GAP_REMAINS|rank_lower={known_rank}|rank_upper=%o|residual_rank_gap=%o|action=complete_two_selmer_or_higher_descent\\n",
        rank_upper, residual_rank_gap;
end if;
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--target", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--mode",
        choices=(
            "selmer-dimension",
            "relative-covers",
            "three-selmer-dimension",
        ),
        default="relative-covers",
    )
    parser.add_argument("--pairing-cover-cap", type=int, default=63)
    args = parser.parse_args()
    if args.pairing_cover_cap < 1:
        parser.error("--pairing-cover-cap must be positive")
    _, target = load_target(args.manifest, args.target)
    manifest_sha256 = sha256_file(args.manifest)
    if args.mode == "selmer-dimension":
        text = build_selmer_dimension_magma(
            target, manifest_sha256=manifest_sha256
        )
    elif args.mode == "three-selmer-dimension":
        text = build_three_selmer_dimension_magma(
            target, manifest_sha256=manifest_sha256
        )
    else:
        text = build_magma(
            target,
            manifest_sha256=manifest_sha256,
            pairing_cover_cap=args.pairing_cover_cap,
        )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    print(f"WROTE {args.output}")
    print(f"TARGET={target['id']}")
    print("PROTOCOL=CFNMSEL_v1")
    print(f"MODE={args.mode}")


if __name__ == "__main__":
    main()

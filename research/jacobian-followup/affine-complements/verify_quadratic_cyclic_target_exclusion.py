"""PF145 exact controls for written mate rigidity and cyclic exclusions."""
from pathlib import Path
import hashlib
import json
import platform
import time
import sympy as S

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
NOTE="JACOBIAN_MATE_RIGIDITY_AND_QUADRATIC_CYCLIC_TARGET_EXCLUSION.md"
CONTEXT="sources/quadratic-cyclic-target-exclusion/context.json"
RECEIPT="quadratic_cyclic_target_exclusion_receipt.json"

def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()

def main():
    started=time.perf_counter()
    checks=[]
    def check(name,value):
        assert bool(value),name
        checks.append(name)
    ctx=json.loads((HERE/CONTEXT).read_text())
    for path,digest in ctx["retained_sha256"].items():
        check("retained source pin "+path,sha(ROOT/path)==digest)

    u,w,z,t,x,H,a,c,b0,chi,alpha,beta=S.symbols("u w z t x H a c b0 chi alpha beta",nonzero=True)
    M=S.Function("M")(u);N=S.Function("N")(u)
    A=S.Function("A")(u);B=S.Function("B")(u);h=S.Function("h")(u)
    surface=w**2-N-M*z
    tau={w:w+M*h,z:z+2*h*w+M*h**2}
    check("translation preserves complete surface equation",
          S.expand(surface.subs(tau,simultaneous=True)-surface)==0)
    inverse={w:w-M*h,z:z-2*h*w+M*h**2}
    check("translation has polynomial inverse on w",
          S.expand(tau[w].subs(inverse,simultaneous=True)-w)==0)
    check("translation has polynomial inverse on z",
          S.expand(tau[z].subs(inverse,simultaneous=True)-z)==0)
    check("translation preserves residue volume",
          S.Matrix([u,w+M*h]).jacobian([u,w]).det()==1)

    E=B-M*A**2/4;D=E-N/M
    P=(w**2-N)/M+A*w+B
    Y=w+M*A/2
    check("square completion identity",S.cancel(P-Y**2/M-D)==0)
    check("first critical equation exact",S.cancel(S.diff(P,w)-2*Y/M)==0)
    check("second critical equation exact at vertex",
          S.simplify(S.diff(P,u).subs(w,-M*A/2)-S.diff(D,u))==0)
    check("critical ideal generated by vertex and D prime",
          S.simplify(S.diff(P,u)-S.diff(D,u)
                     -Y*(2*S.diff(Y,u)/M-Y*S.diff(M,u)/M**2))==0)
    check("unit coefficient along bad fibres",S.diff(z+E,z)==1)

    # These are fixed transcriptions of the unbounded polynomial formulas.
    for k,bu in [(2,u-1),(3,u**2+1),(5,u**2+u+1)]:
        r=S.degree(bu,u)
        sigma=-bu+2*(1-k)*u*S.diff(bu,u)
        mm=u**2*bu**k;nn=u*sigma**2
        check(f"k{k} coprime moving labels",S.gcd(sigma,u*bu)==1)
        check(f"k{k} first multiple fibre smooth",nn.subs(u,0)==0 and S.diff(nn,u).subs(u,0)!=0)
        check(f"k{k} other bad fibres have nonzero w",S.gcd(nn,bu)==1)
        check(f"k{k} first fibre is a double zero of M",mm.subs(u,0)==0 and S.diff(mm,u).subs(u,0)==0)
        for ee in [S.Integer(7),u**2+3*u+1]:
            tag=f"k{k}E{S.degree(ee,u)}"
            TT=S.expand(u**2*bu**(k+1)*S.diff(ee,u)
                        +sigma**2*(bu+k*u*S.diff(bu,u))
                        -2*u*bu*sigma*S.diff(sigma,u))
            DD=ee-nn/mm
            check(tag+" exact critical numerator",
                  S.cancel(S.diff(DD,u)-TT/(u**2*bu**(k+1)))==0)
            check(tag+" no zero-root critical omission",TT.subs(u,0)==bu.subs(u,0)**3)
            check(tag+" no b-root critical omission",
                  S.rem(TT-k*u*S.diff(bu,u)*sigma**2,bu,u)==0)
            check(tag+" critical scheme entirely in D(M)",S.gcd(TT,mm)==1)
            expected=3*r if S.degree(ee,u)==0 else (k+1)*r+S.degree(ee,u)+1
            check(tag+" exact critical scheme length",S.degree(TT,u)==expected)
            # A has arbitrary degree in the proof. This explicit choice
            # checks undoing the automorphism at every scheme root.
            av=u**3+u+1;bv=mm*av**2/4+ee
            pp=(w**2-nn)/mm+av*w+bv
            ww=-mm*av/2
            check(tag+" moving vertex clears first critical equation",
                  S.cancel(S.diff(pp,w).subs(w,ww))==0)
            check(tag+" moving vertex clears second modulo T",
                  S.cancel(S.diff(pp,u).subs(w,ww)-TT/(u**2*bu**(k+1)))==0)

    # One independently checked rational critical point on a scaling-breaking P.
    bu=u-1;k=2;sigma=1-3*u;mm=u**2*bu**2;nn=u*sigma**2
    ff=w**2-nn-mm*z;pp=z+w+mm/4
    point={u:S.Rational(1,3),w:-S.Rational(2,81),z:S.Rational(1,81)}
    check("explicit scaling-breaking coordinate lies on surface",ff.subs(point)==0)
    grads=[S.diff(ff,vv) for vv in [u,w,z]]
    gradp=[S.diff(pp,vv) for vv in [u,w,z]]
    check("explicit point is smooth on surface",any(vv.subs(point)!=0 for vv in grads))
    check("all critical differential minors vanish",
          all(S.cancel((grads[i]*gradp[j]-grads[j]*gradp[i]).subs(point))==0
              for i,j in [(0,1),(0,2),(1,2)]))
    check("example breaks original fibre scaling",S.expand(pp.subs(w,-w)-pp)==-2*w)

    # Exact WHOLE invariant algebra chart for the actual quadratic source image.
    bt=bu.subs(u,t**2);st=sigma.subs(u,t**2);at=t**2*bt**2
    vv=st+at*x;zz=2*st*x+at*x**2;uu=t**2;ww=t*vv
    check("quadratic source chart complete invariant relation",
          S.expand(ww**2-nn.subs(u,uu)-mm.subs(u,uu)*zz)==0)
    check("quadratic source chart volume constant",
          S.expand(S.Matrix([uu,ww]).jacobian([x,t]).det()+2*mm.subs(u,uu))==0)
    check("multiple source line maps isomorphically to C0",zz.subs(t,0)==2*x)

    # Classical S2: critical points OR the residue obstruction, without
    # incorrectly concluding that nonsingularity supplies a mate.
    for ee in [S.Integer(5),u,u**4+u]:
        TT=S.expand(1+u**2*S.diff(ee,u))
        if S.degree(ee,u)==0:
            check("classical nonsingular case survives critical test",TT==1)
        else:
            check(f"classical degree{S.degree(ee,u)} exact critical length",
                  S.degree(TT,u)==S.degree(ee,u)+1)
            check(f"classical degree{S.degree(ee,u)} all critical points away from zero",
                  S.gcd(TT,u)==1)
    aa=S.symbols("aa",nonzero=True)
    cc=aa**2
    uu=(H+1/H-2)/(4*cc)
    ww=(H-1/H)/(4*aa)
    check("generic conic parametrization exact",S.cancel(ww**2-uu-cc*uu**2)==0)
    check("generic conic H coordinate exact",S.cancel(1+2*cc*uu+2*aa*ww-H)==0)
    differential=S.cancel(-S.diff(uu,H)/(2*ww))
    check("coframe on generic conic has logarithmic pole",
          S.cancel(differential+1/(2*aa*H))==0)
    check("nonzero residue excludes rational primitive",
          S.residue(differential,H,0)==-1/(2*aa))
    check("smooth scaling-breaking classical candidate",
          S.expand((w**2-u)/u**2+w+u**2/4
                   -(w+u**2/2)**2/u**2+1/u)==0)

    # Actual constant-Jacobian mate rigidity transcribed independently.
    p,q=S.symbols("p q")
    hp=S.Function("hp")(p)
    target=S.Matrix([alpha*p+beta,(chi/alpha)*q+hp])
    check("forced triangular target action has exact determinant",
          target.jacobian([p,q]).det()==chi)
    check("polynomial mate difference centralizes first coordinate",
          S.diff(hp,q)==0)
    check("closedness fails for composite non-Keller coordinate",
          S.diff(x**2,x).subs(x,0)==0)

    out=dict(claim="PF2RULED145",outcome="PASS",check_count=len(checks),checks=checks,
             elapsed_seconds=time.perf_counter()-started,
             environment=dict(python=platform.python_version(),sympy=S.__version__),
             proof_sha256=sha(HERE/NOTE),checker_sha256=sha(Path(__file__)),
             context_sha256=sha(HERE/CONTEXT),
             arbitrary_target_coordinates_classified=False,
             automatic_marked_quadratic_regularity=False,
             unrestricted_cyclic_targets_excluded=False,full_goal_complete=False,
             registered_predecessor_checkers_replayed=[],
             independent_replay=False,formal_verification=False,external_review=False)
    (HERE/RECEIPT).write_text(json.dumps(out,indent=2)+"\n")
    print(json.dumps({key:out[key] for key in ["claim","outcome","check_count","elapsed_seconds"]}))

if __name__=="__main__":
    main()

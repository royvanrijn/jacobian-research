#!/usr/bin/env python3
"""Seek exact two-generator upper certificates for the fixed cover groups.

Only successful elementary free-automorphism reductions are certificates.
A bounded miss is not a lower bound or a non-primitivity theorem.
"""

from functools import reduce
import hashlib
from itertools import product
import json
from math import gcd
from pathlib import Path
import time

from parabolic_lifts import oriented_diagram

HERE=Path(__file__).resolve().parent


def inverse(word):
    return [-x for x in reversed(word)]


def free_reduce(word):
    stack=[]
    for x in word:
        if stack and stack[-1]==-x:
            stack.pop()
        else:
            stack.append(x)
    return stack


def cyclic_reduce(word):
    w=free_reduce(word)
    while len(w)>1 and w[0]==-w[-1]:
        w=w[1:-1]
    return w


def substitute(word,images):
    return free_reduce([x for g in word for x in (images[g-1] if g>0 else inverse(images[-g-1]))])


def automorphisms():
    result=[]
    alphabet=[1,-1,2,-2,3,-3]
    for a in alphabet:
        others=[x for x in alphabet if abs(x)!=abs(a)]
        for flags in product([0,1],repeat=4):
            chosen={a}|{x for x,flag in zip(others,flags) if flag}
            images=[]
            backwards=[]
            for x in [1,2,3]:
                if abs(x)==abs(a):
                    images.append([x]);backwards.append([x])
                else:
                    images.append(([-a] if -x in chosen else [])+[x]+([a] if x in chosen else []))
                    backwards.append(([a] if -x in chosen else [])+[x]+([-a] if x in chosen else []))
            assert all(substitute(images[i],backwards)==[i+1] and substitute(backwards[i],images)==[i+1] for i in range(3))
            result.append({"multiplier":a,"subset":sorted(chosen),"images":images,"inverse_images":backwards})
    assert len(result)==96
    return result


def core_presentation(case,source):
    seeds=source["seeds"]
    words={seeds[0]:[]}
    words.update({s:[i+1] for i,s in enumerate(seeds[1:])})
    for over,a,b in source["seed_trace"]:
        assert b not in words and over in words and a in words
        words[b]=free_reduce(words[over]+inverse(words[a])+words[over])
    assert set(words)==set(range(13))
    relators=[free_reduce(words[o]+inverse(words[a])+words[o]+inverse(words[b])) for o,a,b,_ in oriented_diagram(case["pd"])]
    return [words[i] for i in range(13)],relators


def primitive_reduction(word,autos,deadline):
    current=cyclic_reduce(word)
    vector=[sum(x==i for x in current)-sum(x==-i for x in current) for i in [1,2,3]]
    if reduce(gcd,map(abs,vector),0)!=1:
        return None,0
    steps=[]
    trials=0
    while len(current)>1:
        assert time.monotonic()<deadline
        best,best_index=current,None
        for i,automorphism in enumerate(autos):
            trials+=1
            candidate=cyclic_reduce(substitute(current,automorphism["images"]))
            if len(candidate)<len(best):
                best,best_index=candidate,i
        if best_index is None:
            return None,trials
        steps.append(best_index)
        current=best
    if current:
        return {"automorphism_indices":steps,"final_relator":current},trials
    return None,trials


def candidates(relators):
    nonempty=[i for i,w in enumerate(relators) if cyclic_reduce(w)]
    for i in nonempty:
        yield [{"relator_index":i,"exponent":1,"conjugator":[]}]
    for i,j,sign_i,sign_j,conjugator in product(nonempty,nonempty,[1,-1],[1,-1],[[],[1],[-1],[2],[-2],[3],[-3]]):
        yield [{"relator_index":i,"exponent":sign_i,"conjugator":[]},
               {"relator_index":j,"exponent":sign_j,"conjugator":conjugator}]


def consequence(terms,relators):
    return free_reduce([x for term in terms for x in term["conjugator"]+
                        (relators[term["relator_index"]] if term["exponent"]==1 else inverse(relators[term["relator_index"]]))+
                        inverse(term["conjugator"])])


def main():
    panel=json.loads((HERE/"joint_a5_panel.json").read_text())["cases"][:16]
    sources=json.loads((HERE/"joint_a5_results.json").read_text())["results"][:16]
    inputs=["joint_a5_panel.json","joint_a5_results.json","joint_a5_verification.json","six_point_cover_results.json"]
    plan={"status":"FROZEN_BEFORE_GENERATOR_REDUCTION","targets":[c["name"] for c in panel],
          "motivation":"The completed degree5 and preliminary degree6 homology gains are tiny. If a primitive word in the relation normal closure is certified, the actual double-cover group is generated by two elements, closing every rank>=3 approach for that group rather than enlarging coefficient sweeps.",
          "selection":"Exactly the same16 diagrams and their existing normalized four-seed core presentations; no replacements",
          "method":"All direct relators then products of two signed relators with the second conjugated by a word of length at most1. Greedy length reduction by all96 explicit rank3 Whitehead automorphisms. Only success is conclusive.",
          "limits":{"candidates_per_case":500,"seconds_per_case":10,"total_seconds":120,"checkpoint_after_each_case":True},
          "failure_scope":"A miss only concerns the frozen candidate words and greedy choices, not arbitrary primitive consequences or group rank",
          "input_sha256":{p:hashlib.sha256((HERE/p).read_bytes()).hexdigest() for p in inputs}}
    path=HERE/"core_generator_plan.json"
    if not path.exists():
        path.write_text(json.dumps(plan,indent=2)+"\n")
        print("FROZEN core_generator_plan.json; rerun to execute")
        return
    assert json.loads(path.read_text())==plan
    inputs += ["audit_core_generators.py","core_generator_plan.json","parabolic_lifts.py"]
    hashes={p:hashlib.sha256((HERE/p).read_bytes()).hexdigest() for p in inputs}
    output=HERE/"core_generator_results.json"
    report=json.loads(output.read_text()) if output.exists() else {"status":"RUNNING","results":[],"input_sha256":hashes}
    assert report["input_sha256"]==hashes
    autos=automorphisms()
    done={r["name"] for r in report["results"]}
    start=time.monotonic()
    for case,source in zip(panel,sources):
        assert case["name"]==source["name"]
        if case["name"] in done:
            continue
        if time.monotonic()-start>=120:
            break
        deadline=min(start+120,time.monotonic()+10)
        arc_words,relators=core_presentation(case,source)
        seen=set()
        checks=trials=0
        certificate=None
        state="BOUNDED_MISS"
        try:
            for terms in candidates(relators):
                word=consequence(terms,relators)
                key=tuple(cyclic_reduce(word))
                if not key or key in seen:
                    continue
                seen.add(key)
                if checks>=500:
                    state="CANDIDATE_LIMIT";break
                checks+=1
                reduced,count=primitive_reduction(word,autos,deadline)
                trials+=count
                if reduced is not None:
                    certificate={"consequence_terms":terms,"primitive_word":word,**reduced}
                    state="TWO_GENERATOR_CERTIFICATE";break
        except AssertionError:
            assert time.monotonic()>=deadline
            state="TIME_LIMIT"
        row={"name":case["name"],"status":state,"seeds":source["seeds"],"seed_trace":source["seed_trace"],
             "arc_words":arc_words,"three_generator_relators":relators,"candidates":checks,"automorphism_trials":trials,
             "certificate":certificate}
        report["results"].append(row)
        output.write_text(json.dumps(report,indent=2)+"\n")
        print(json.dumps({"name":row["name"],"status":state,"relator_lengths":[len(w) for w in relators],"candidates":checks}),flush=True)
    report.update({"status":"COMPLETE" if len(report["results"])==16 else "CHECKPOINTED","automorphisms":autos})
    output.write_text(json.dumps(report,indent=2)+"\n")
    print(json.dumps({"status":report["status"],"two_generator_certificates":sum(r["certificate"] is not None for r in report["results"])}))


if __name__=="__main__":
    main()

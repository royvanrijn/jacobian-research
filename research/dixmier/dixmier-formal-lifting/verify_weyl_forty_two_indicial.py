"""Exact local indicial list for the order-(12,42) resultant.

The proof reduces the indicial divisor and mean constraints
to gap ideals of the numerical semigroup generated by 6,17,21.
This checker enumerates those ideals and reconstructs all
three effective root divisors. It does not test completion.
"""

from collections import Counter


SHIFTS = (6, 17, 21)
CONDUCTOR = 50


def semigroup_gaps():
    present = {0}
    for value in range(1, CONDUCTOR + min(SHIFTS)):
        if any(value - step in present for step in SHIFTS):
            present.add(value)
    assert CONDUCTOR - 1 not in present
    assert set(range(CONDUCTOR, CONDUCTOR + min(SHIFTS))) <= present
    return sorted(set(range(CONDUCTOR)) - present)


def gap_ideals(gaps):
    ideals = [frozenset()]
    for gap in gaps:
        predecessors = {gap - step for step in SHIFTS if gap - step in gaps}
        ideals.extend(ideal | {gap}
                      for ideal in tuple(ideals) if predecessors <= ideal)
    return ideals


def primitive_divisor(ideal):
    divisor = Counter({0: 1})
    previous = 0
    for index in range(CONDUCTOR + 1):
        current = int(index not in ideal)
        divisor[index - len(ideal)] += current - previous
        previous = current
    return divisor


def check_indicial_list():
    gaps = semigroup_gaps()
    assert len(gaps) == 25
    ideals = gap_ideals(gaps)
    assert len(set(ideals)) == len(ideals) == 1694

    candidates = set()
    for ideal in ideals:
        divisor = primitive_divisor(ideal)
        assert sum(divisor.values()) == 2
        assert sum(root*mass for root, mass in divisor.items()) == 0
        candidates.add(tuple(sorted((root, mass) for root, mass in divisor.items() if mass)))

        for shift in SHIFTS:
            roots = Counter()
            for root, mass in divisor.items():
                if mass:
                    for offset in range(shift):
                        roots[root + offset] += mass
            assert sum(roots.values()) == 2*shift
            assert all(mass >= 0 for mass in roots.values())
            assert all(roots[root] >= 1 for root in range(shift))
            assert sum(root*mass for root, mass in roots.items()) == shift*(shift-1)
    assert len(candidates) == 1694


if __name__ == "__main__":
    check_indicial_list()
    print("Checked the 1694 distinct indicial divisor candidates at shifts 6, 17 and 21.")

"""Exact controls for global reconstruction and embedding obstructions.

The arbitrary-degree commutative-algebra and hypersurface arguments
are written proofs. These controls do not certify external theorems.
"""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import time

import sympy as S

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path)
    args = parser.parse_args()
    started = time.monotonic()
    checks = []

    def check(name,value):
        if not value:
            raise AssertionError(name)
        checks.append(name)

    def zero(name,value):
        values = list(value) if isinstance(value,S.MatrixBase) else [value]
        check(name,all(S.cancel(item.doit())==0 for item in values))

    s,U,P,Q,Y1,Y2,T,c = S.symbols('s U P Q Y1 Y2 T c')
    coeffs = S.symbols('a0:5')
    relation = sum(coeffs[ii]*T**ii for ii in range(5))
    check('a relation derivative minus a scalar has strictly smaller T degree',
          S.degree(S.diff(relation,T)-c,T)<S.degree(relation,T))
    derivative = S.Poly(S.diff(relation,T)-c,T)
    check('zero derivative difference kills every higher term in characteristic zero',
          [derivative.nth(ii) for ii in range(4)]==[coeffs[1]-c,2*coeffs[2],3*coeffs[3],4*coeffs[4]])

    # An honest automorphic example has only a linear extra-generator relation.
    F,G = s,U+s**3
    h = s*s+U
    R = T-Y1*Y1-Y2+Y1**3
    zero('the single-generator relation is exact on an automorphic control',
         R.subs({Y1:F,Y2:G,T:h},simultaneous=True))
    zero('the single-generator derivative is the required field unit',S.diff(R,T)-1)
    zero('the Keller differential matrix has its exact polynomial inverse',
         S.Matrix([F,G]).jacobian((s,U))*S.Matrix([[1,0],[-3*s*s,1]])-S.eye(2))
    zero('the recovered source coordinates give an actual inverse',
         S.Matrix([F,G]).subs({s:Y1,U:Y2-Y1**3},simultaneous=True)-S.Matrix([Y1,Y2]))

    # The hypotheses of the classical criterion cannot be silently dropped.
    ramified = S.Matrix([s*s,U])
    zero('one extra polynomial alone is insufficient without the Keller condition',
         ramified.jacobian((s,U)).det()-2*s)
    zero('the ramified monogenic control has a nonunit relation derivative',
         S.diff(T*T-Y1,T).subs(T,s)-2*s)
    localization_relation = Y1*T-1
    zero('the localization control is an exact unramified hypersurface relation',
         localization_relation.subs({Y1:s,T:1/s},simultaneous=True))
    zero('localization enlarges units so its derivative need not be scalar',
         S.diff(localization_relation,T).subs(Y1,s)-s)
    artin_schreier = S.Poly(T**5-T-Y1,T,Y1,modulus=5)
    check('positive characteristic permits a nonlinear relation with constant derivative',
          artin_schreier.diff(T)==S.Poly(-1,T,Y1,modulus=5) and artin_schreier.degree(T)==5)
    A = (s-1)*(s-2)
    B = 2*s-3
    check('a reduced multi-point fibre is generated by one separating function',
          S.degree(A,s)==2 and S.gcd(A,S.diff(A,s))==1)
    check('that fibre generator need not give global recovery, non-Keller control',
          S.Matrix([A,B*U,s]).subs(s,S.Rational(3,2)).diff(U)==S.zeros(3,1))

    # Cotangent gradient targets plus two base coordinates recover every source.
    D = s**3+U*U
    potential = D+P*F+Q*G
    variables = (s,U,P,Q)
    outputs = S.Matrix([S.diff(potential,z) for z in variables])
    eta = outputs[:2,0]
    jac = S.Matrix([F,G]).jacobian((s,U))
    wb = jac.T.inv()*(eta-S.Matrix([S.diff(D,s),S.diff(D,U)]))
    zero('two additional base coordinates give exact global cotangent source recovery',wb-S.Matrix([P,Q]))
    eta1,eta2 = S.symbols('eta1 eta2')
    formal_w = jac.T.inv()*(S.Matrix([eta1,eta2])-S.Matrix([S.diff(D,s),S.diff(D,U)]))
    zero('the polynomial source recovery works on every complementary gradient target',
         outputs.subs({P:formal_w[0],Q:formal_w[1]},simultaneous=True)-S.Matrix([eta1,eta2,F,G]))
    zero('the cotangent source change is a polynomial automorphism',
         S.Matrix([s,U,outputs[0],outputs[1]]).jacobian(variables).det()-1)
    zero('this reconstruction control has actual unit full Hessian',S.hessian(potential,variables).det()-1)

    # The fixed physical fibre closes every embedded exact GF3 encoding.
    x,y,p,q,r,L,M,N = S.symbols('x y p q r L M N')
    u = 1+x*y
    ambient_A = u**3*p+3*x*u**2*q-x**3*r
    ambient_B = y*y*u*(4+3*x*y)*p+(y+3*x*y*y*(4+3*x*y))*q+(2*x-3*x*x*y)*r
    zero('the physical A row at base (0,1) is exactly p',ambient_A.subs({x:0,y:1},simultaneous=True)-p)
    zero('the physical B row at base (0,1) is exactly 4p plus q',ambient_B.subs({x:0,y:1},simultaneous=True)-(4*p+q))
    zero('the physical fibre frame has an actual linear inverse',
         S.Matrix([p,4*p+q,r]).subs({p:Y1,q:Y2-4*Y1,r:T},simultaneous=True)-S.Matrix([Y1,Y2,T]))
    fibre_map = S.Matrix([F,G-4*F,s*U+U**3])
    zero('a genuine automorphic pair gives polynomial recovery on that closed plane',
         S.Matrix([p,q+4*p-p**3]).subs({p:fibre_map[0],q:fibre_map[1]},simultaneous=True)-S.Matrix([s,U]))
    encoded = L*F*F+M*F+N*(x*F+y*G)
    zero('the exact cotangent encoding has its asserted actual full Hessian',
         S.hessian(encoded,(x,y,s,U)).det()-N**4)
    native_grad = S.Matrix([S.diff(encoded,z) for z in (x,y,s,U)])
    t0,t1,t2,t3 = S.symbols('t0:4')
    sb = t0/N
    ub = t1/N-sb**3
    yb = (t3)/N
    xb = (t2-(2*L*sb+M))/N-3*sb*sb*yb
    zero('the embedded independent-pair encoding has an actual gradient inverse',
         native_grad.subs({s:sb,U:ub,x:xb,y:yb},simultaneous=True)-S.Matrix([t0,t1,t2,t3]))

    # A target-dependent affine fibre frame, with fully source-dependent offsets.
    H = S.Matrix([[1,Y1,0],[0,1,Y2],[Y2,Y1*Y2,1]])
    linear_columns = H[:,:2]
    cross = linear_columns[:,0].cross(linear_columns[:,1])
    zero('the target-dependent frame is unimodular',H.det()-1)
    zero('the cross product is the exact polynomial annihilator',cross-S.Matrix([-Y2,0,1]))
    zero('the matrix columns are annihilated without a field-only inverse',linear_columns.T*cross)
    zero('the cross product has an explicit polynomial Bezout completion',(cross.T*H[:,2])[0]-1)
    offsets = S.Matrix([s*s+U,U*U,s*U+s**3])
    kvals = {Y1:F,Y2:G}
    physical_duals = linear_columns.subs(kvals,simultaneous=True)*S.Matrix([P,Q])+offsets
    d1,d2,d3 = S.symbols('d1 d2 d3')
    htarget = (cross.subs(kvals,simultaneous=True).T*offsets)[0].subs(
        {s:Y1,U:Y2-Y1**3},simultaneous=True)
    E = (cross.T*S.Matrix([d1,d2,d3]))[0]-htarget
    zero('the positive affine-fibre control lies on its exact closed hypersurface',
         E.subs({Y1:F,Y2:G,d1:physical_duals[0],d2:physical_duals[1],d3:physical_duals[2]},simultaneous=True))
    zero('the defining polynomial has its target-descended dual normal',
         S.Matrix([S.diff(E,dv) for dv in (d1,d2,d3)])-cross)
    zero('the closed hypersurface is smooth in the positive control',S.diff(E,d3)-1)
    pulled_back_frame = H.inv().subs(kvals,simultaneous=True)*(physical_duals-offsets)
    zero('the actual affine-fibre source variables have polynomial recovery',pulled_back_frame-S.Matrix([P,Q,0]))
    rank_drop = S.Matrix([[Y1,0],[0,Y2],[Y2,Y1]])
    mdrop = rank_drop[:,0].cross(rank_drop[:,1])
    zero('a target rank-drop matrix still has the exact polynomial kernel identity',rank_drop.T*mdrop)
    check('a target rank drop on an automorphic image destroys source immersiveness',
          rank_drop.subs({Y1:0,Y2:0},simultaneous=True).rank()<2)
    high_dual = (Y1*d1+d2*d3)**3+d1*d2
    check('differentiation strictly lowers total dual degree for nonzero partials',
          all(S.Poly(S.diff(high_dual,dv),d1,d2,d3).total_degree()
              <S.Poly(high_dual,d1,d2,d3).total_degree() for dv in (d1,d2,d3)))

    dependencies = {}
    for proof,receipt_name in [('FIRST_SLICE_INVERTIBILITY.md','receipt-first-slice.json'),
                               ('FINITE_FIBRE_NORMAL_FORM.md','receipt-finite-fibre.json'),
                               ('GLOBAL_VALUE_ORBITS.md','receipt-global-value.json')]:
        receipt = json.loads((HERE/receipt_name).read_text())
        digest = hashlib.sha256((HERE/proof).read_bytes()).hexdigest()
        check('retained proof pin '+proof,digest==receipt['source_sha256'][proof])
        dependencies[str((HERE/proof).relative_to(ROOT))] = digest
    row_proof = 'hessian/hc4-relative-row-orbit/PROOF.md'
    digest = hashlib.sha256((ROOT/row_proof).read_bytes()).hexdigest()
    check('retained birational Keller input',digest==json.loads((HERE/'receipt-square-axis.json').read_text())['dependencies'][row_proof])
    dependencies[row_proof] = digest
    tang = json.loads((ROOT/'hessian/tang-hc4-audit/structural-proof-receipt.json').read_text())['source_proof_and_replay_sha256']
    for name in ['hessian/tang-hc4-audit/STRUCTURAL_REVIEW.md',
                 'hessian/tang-hc4-audit/source-v1.pdf']:
        digest = hashlib.sha256((ROOT/name).read_bytes()).hexdigest()
        check('retained Tang input '+name,digest==tang[name])
        dependencies[name] = digest
    manifest = json.loads((HERE/'sources/reconstruction-import.json').read_text())
    for source in manifest['sources']:
        path = HERE/'sources'/source['retained_file']
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        check('inspected primary algebra or bibliographic source '+path.name,digest==source['sha256'])
        dependencies[str(path.relative_to(ROOT))] = digest
    check('the classical result is credited and subscription full text is not falsely claimed read',
          manifest['general_single_generator_criterion_asserted_new'] is False
          and manifest['original_subscription_full_text_asserted_read'] is False)
    result = dict(outcome='PASS',check_count=len(checks),checks=checks,
        source_sha256={name:hashlib.sha256((HERE/name).read_bytes()).hexdigest()
                       for name in [Path(__file__).name,'RECONSTRUCTION_EMBEDDING_OBSTRUCTION.md','sources/reconstruction-import.json']},
        dependencies=dependencies,
        written_not_finite_exhaustion=['classical single-generator Keller criterion with a complete characteristic-zero proof',
            'global one-common-helper HC4 reconstruction and exact two-helper minimum under nonautomorphy',
            'no closed-embedded nonautomorphic exact A=F, B=xF+yG cotangent encoding in any degree',
            'hypersurface dual-normal argument excludes all target-dependent affine fibre encodings',
            'the affine-fibre obstruction allows matrix rank drop away from the Keller image'],
        classical_Formanek_criterion_asserted_new=False,
        closed_embedding_inferred_from_finite_fibre_generation=False,
        closed_embedding_inferred_from_field_primitive_element=False,
        general_graph_embedding_asserted_over_gradient_projection=False,
        two_helper_minimum_asserted_as_absolute_embedding_dimension=False,
        affine_fibre_matrix_required_globally_split=False,
        source_dependent_or_nonlinear_dual_frames_asserted_closed=False,
        original_subscription_full_text_asserted_read=False,
        nonlinear_Hessian_invariance_used=False,
        universal_SL2_row_equation_solved=False,
        unit_ideal_plane_Keller_endpoint_resolved=False,singleton_zero_properness_resolved=False,
        unrestricted_HC4_or_JC2_resolved=False,
        formal_verification=False,independent_replay=False,external_review=False,
        runtime=dict(python=platform.python_version(),sympy=S.__version__),
        elapsed_seconds=round(time.monotonic()-started,3))
    rendered = json.dumps(result,indent=2)+'\n'
    if args.output:
        args.output.write_text(rendered)
    print(rendered,end='')


if __name__=='__main__':
    main()

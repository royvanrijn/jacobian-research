START = time.perf_counter()
checks: list[dict[str, object]] = []


def check(name: str, condition: object) -> None:
    result = bool(condition)
    checks.append({"name": name, "passed": result})
    if not result:
        raise AssertionError(name)


def eq(name: str, actual: object, expected: object) -> None:
    check(name, S.cancel(S.sympify(actual) - S.sympify(expected)) == 0)


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# Degrees in the actual closed/open BM sequence, with ordinary PD cohomology.
bm_x = {4: 1}
for i in [1, 2]:
    check(f"BM(D)->BM(U) is isolated by zero source terms in degree{i}",
          bm_x.get(i + 1, 0) == bm_x.get(i, 0) == 0)
eq("BM degree1 corresponds to ordinary H3 on a four-manifold", 4 - 1, 3)
eq("BM degree2 corresponds to ordinary H2 on a four-manifold", 4 - 2, 2)
check("affine complex surface CW dimension excludes ordinary H3", 3 > 2)
check("loop general position misses real two-dimensional boundary", 1 + 2 < 4)
check("isolated point has surface codimension two", 2 - 0 == 2)

# Explicit integral branch summation. Its kernel is generated by differences
# within each normalization fibre, and SNF proves no hidden torsion.
patterns = [(1,), (2,), (3,), (1, 1), (2, 2), (1, 3, 2), (4, 1, 2)]
for pattern in patterns:
    rows, cols = len(pattern), sum(pattern)
    M = S.zeros(rows, cols)
    kernel_columns = []
    offset = 0
    for row, branches in enumerate(pattern):
        for j in range(branches):
            M[row, offset + j] = 1
        for j in range(1, branches):
            col = S.zeros(cols, 1)
            col[offset] = -1
            col[offset + j] = 1
            kernel_columns.append(col)
        offset += branches
    K = S.Matrix.hstack(*kernel_columns) if kernel_columns else S.zeros(cols, 0)
    label = str(pattern)
    eq("branch summation is surjective rank " + label, M.rank(), rows)
    eq("branch excess equals kernel rank " + label, cols - M.rank(),
       sum(r - 1 for r in pattern))
    check("all explicit branch differences are killed " + label,
          M * K == S.zeros(rows, K.cols))
    eq("branch differences have full kernel rank " + label, K.rank(), cols - rows)
    snf = smith_normal_form(M, domain=ZZ)
    check("branch summation has torsion-free cokernel " + label,
          all(abs(snf[j, j]) == 1 for j in range(rows)))
    check("zero branch excess means every fibre is single " + label,
          (cols == rows) == all(r == 1 for r in pattern))

# The normalization formula is rank(H1BM)=sum(2g+s-1)+branch excess.
# These finite controls illustrate nonnegative terms; Section4 proves the
# unrestricted implication without a bound on g,s,number of components.
curve_cases = {
    "affine line": ([(0, 1)], [], 0, 1),
    "punctured affine line": ([(0, 2)], [], 1, 0),
    "once-punctured elliptic curve": ([(1, 1)], [], 2, -1),
    "affine nodal rational curve": ([(0, 1)], [2], 1, 0),
    "two affine lines crossing once": ([(0, 1), (0, 1)], [2], 1, 1),
    "three affine lines in a chain": ([(0, 1)] * 3, [2, 2], 2, 1),
    "cuspidal affine line topological control": ([(0, 1)], [1], 0, 1),
    "two disjoint affine lines": ([(0, 1)] * 2, [], 0, 2),
}
for name, (components, branches, expected_h1, expected_euler) in curve_cases.items():
    h1 = sum(2 * g + s - 1 for g, s in components) + sum(r - 1 for r in branches)
    euler = sum(2 - 2 * g - s for g, s in components) - sum(r - 1 for r in branches)
    eq("curve BM rank " + name, h1, expected_h1)
    eq("curve compact-support Euler " + name, euler, expected_euler)
    eq("curve BM Euler degree ledger " + name, len(components) - h1, euler)
for g in range(3):
    for punctures in range(1, 5):
        for excess in range(3):
            rank = 2 * g + punctures - 1 + excess
            check(f"nonnegative normalization terms g{g}s{punctures}e{excess}",
                  (rank == 0) == (g == 0 and punctures == 1 and excess == 0))

# Cusps really pass the topological test while failing smoothness. This is
# a sharpness control for the curve implication, not a claimed Keller pair.
x, y, t, s, T, alpha = S.symbols("x y t s T alpha")
cusp = y**2 - x**3
eq("cusp parametrization satisfies its equation",
   cusp.subs({x: t**2, y: t**3}), 0)
eq("cusp normalization parameter is rational", (t**3)/(t**2), t)
eq("cusp parameter is integral over its image", (T**2 - x).subs({T:t, x:t**2}), 0)
eq("cusp x derivative vanishes at singular point", S.diff(t**2, t).subs(t, 0), 0)
eq("cusp y derivative vanishes at singular point", S.diff(t**3, t).subs(t, 0), 0)
eq("cusp defining x-gradient vanishes", S.diff(cusp, x).subs({x:0, y:0}), 0)
eq("cusp defining y-gradient vanishes", S.diff(cusp, y).subs({x:0, y:0}), 0)
eq("normalization generically separates the parameter",
   S.Poly(t**2-s**2, t, domain=S.QQ.frac_field(s)).gcd(
       S.Poly(t**3-s**3, t, domain=S.QQ.frac_field(s))).as_expr(), t-s)
semigroup = {2*a + 3*b for a in range(10) for b in range(10)}
check("cusp ring omits the degree-one normalization parameter", 1 not in semigroup)
check("cusp ring contains every tested exponent at least conductor two",
      all(n in semigroup for n in range(2, 19)))
check("cusp embedding dimension exceeds curve dimension", 2 > 1)

# Closed polynomial curve image: one nonconstant source restriction gives a
# finite integral parameter extension. Exact reductions control all needed
# monic normalization and module-generation algebra in representative degrees.
for d in range(2, 7):
    monic = T**d + T - alpha
    eq(f"monic parameter equation d{d}",
       monic.subs({T:t, alpha:t**d+t}), 0)
    for power in [d, d+1, 2*d+1]:
        remainder = S.rem(T**power, monic, T)
        check(f"finite module remainder degree d{d} power{power}",
              S.degree(remainder, T) < d)
        eq(f"finite module reduction exact d{d} power{power}",
           remainder.subs({T:t, alpha:t**d+t}), t**power)

# Exact target coframe/inverse vector fields on genuine polynomial Keller
# coordinate controls. No assertion that arbitrary etale vector fields are LND.
pairs = [
    (x+y**2, y),
    (x, y+x**3),
    (2*(x+y**2), y+(x+y**2)**2),
]
for index, (P, Q) in enumerate(pairs):
    jac = S.expand(S.diff(P,x)*S.diff(Q,y)-S.diff(P,y)*S.diff(Q,x))
    check(f"coordinate control has nonzero constant Jacobian {index}",
          jac != 0 and not jac.free_symbols)
    DP = lambda f: S.expand((S.diff(Q,y)*S.diff(f,x)-S.diff(Q,x)*S.diff(f,y))/jac)
    DQ = lambda f: S.expand((-S.diff(P,y)*S.diff(f,x)+S.diff(P,x)*S.diff(f,y))/jac)
    eq(f"pulled-back target derivation P(P) {index}", DP(P), 1)
    eq(f"pulled-back target derivation P(Q) {index}", DP(Q), 0)
    eq(f"pulled-back target derivation Q(P) {index}", DQ(P), 0)
    eq(f"pulled-back target derivation Q(Q) {index}", DQ(Q), 1)
    for generator in [x, y]:
        eq(f"target derivations commute on {generator} model{index}",
           DP(DQ(generator))-DQ(DP(generator)), 0)
    eq(f"canonical volume pulls back to source unit {index}", jac/jac, 1)
    # d(P dQ) has exactly the Jacobian coefficient in dx wedge dy.
    primitive_coeff = S.diff(P*S.diff(Q,y),x)-S.diff(P*S.diff(Q,x),y)
    eq(f"canonical source volume is exact model{index}", primitive_coeff/jac, 1)

D = lambda f: S.expand(x*S.diff(f,x)-y*S.diff(f,y))
eq("generic unit-volume Hamiltonian contraction x coefficient", -D(y), y)
eq("generic unit-volume Hamiltonian contraction y coefficient", D(x), x)
f = x
for n in range(1, 6):
    f = D(f)
    eq(f"regular Hamiltonian alone need not be LND n{n}", f, x)

# Numerical consequences of a free finite deck action. These do not prove a
# new finite group action or assume that a deck group preserves the source.
for g, multiple, quotient_euler in [(2,3,1), (3,2,2), (4,3,1), (5,2,3), (6,2,2)]:
    degree = g*multiple
    b0 = g*quotient_euler-1
    check(f"free deck Euler divisibility g{g}", (b0+1) % g == 0)
    check(f"generic fixed-field divisibility g{g}", degree % g == 0)
    check(f"combined gcd divisibility g{g}", S.igcd(degree,b0+1) % g == 0)
    check(f"nontrivial free deck requires positive boundary g{g}", b0 > 0)
    for shift in [1, g-1]:
        check(f"nonidentity regular fibre action has no fixed point g{g}r{shift}",
              all((j+shift) % g != j for j in range(g)))
eq("no-boundary Euler count is one", 1+0, 1)
check("positive divisor of no-boundary Euler must be one",
      S.divisors(1) == [1])


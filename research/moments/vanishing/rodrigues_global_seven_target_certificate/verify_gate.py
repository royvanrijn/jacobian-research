"""Replay the exact inputs to the seven-condition global gate.

No global power membership is asserted or tested here.
"""
from contextlib import redirect_stdout, redirect_stderr
from pathlib import Path
import hashlib
import importlib
import json
import subprocess
import sys
import time

root = Path(__file__).resolve().parent
sys.path.insert(0, str(root))
started = time.monotonic()

baseline = root / 'rodrigues_local_length17_certificate'
manifest = json.loads((baseline / 'manifest.json').read_text())
actual_hash = hashlib.sha256((baseline / 'certificate_data.json').read_bytes()).hexdigest()
assert actual_hash == manifest['sha256']['certificate_data.json']
print('Retained local certificate hash: PASS', flush=True)

outputs = [root / name for name in (
    'global_target_nilindices.json',
    'global_adapted_targets.json',
    'global_cubic_relation.json',
)]
outputs.append(root / 'odd_slice_support_certificate' / 'odd_slice_support_data.json')
expected = {path: path.read_bytes() for path in outputs}

for module in ('global_target_nilindices', 'global_adapted_targets', 'global_cubic_relation'):
    with (root / (module + '.log')).open('w') as log:
        with redirect_stdout(log), redirect_stderr(log):
            importlib.import_module(module)
    print(module + ': PASS', flush=True)

support = root / 'odd_slice_support_certificate'
with (support / 'verification.log').open('w') as log:
    subprocess.run([sys.executable, str(support / 'verify_odd_slice.py')],
                   cwd=support, stdout=log, stderr=subprocess.STDOUT, check=True)
print('Complete cyclic support and scheme certificate: PASS', flush=True)

for path in outputs:
    assert path.read_bytes() == expected[path], 'Regenerated JSON differs: ' + str(path)
print('All four new JSON outputs regenerated byte-for-byte: PASS', flush=True)

# Check the exact integer export without introducing floating-point division.
from fractions import Fraction
cubic = json.loads((root / 'global_cubic_relation.json').read_text())
coefficients = [Fraction(x) for x in cubic['coefficients']]
assert coefficients == [
    Fraction(1),
    Fraction(55782484748580, 23118017560861),
    -Fraction(1009306881744, 399965701745),
    -Fraction(34813910270351, 13198868157585),
    -Fraction(119786979, 79993140349),
]
integers = [3814472897542065, 9204109983515700, -9625759731192528,
            -10061220068131439, -5712042093615]
assert all(Fraction(x, integers[0]) == c for x, c in zip(integers, coefficients))
print('Exact cubic coefficients and primitive integer normalization: PASS', flush=True)
print('ALL GLOBAL-GATE INPUT CHECKS PASSED.', flush=True)
print('Global membership identities and length 51 remain unproved.', flush=True)
print('Elapsed seconds:', time.monotonic() - started, flush=True)

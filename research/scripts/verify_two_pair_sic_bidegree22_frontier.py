def moment_terms(
    support: tuple[int, ...], order: int
) -> dict[tuple[int, ...], int]:
    """Return the exact coefficient polynomial for E_2(f^order).

    The exponent pair (i,j) records the V-degree and Y-degree of M_ij.
    A term survives precisely when the total V- and Y-degrees agree.
    """

    support_size = len(support)
    polynomial = {(0, 0, (0,) * support_size): 1}
    for _ in range(order):
        product: dict[tuple[int, int, tuple[int, ...]], int] = {}
        for (dual_v, coordinate_y, exponents), coefficient in polynomial.items():
            for position, monomial_index in enumerate(support):
                i, j = MONOMIALS[monomial_index]
                new_exponents = list(exponents)
                new_exponents[position] += 1
                key = (
                    dual_v + i,
                    coordinate_y + j,
                    tuple(new_exponents),
                )
                product[key] = product.get(key, 0) + coefficient
        polynomial = product

    result: dict[tuple[int, ...], int] = {}
    for (dual_v, coordinate_y, exponents), coefficient in polynomial.items():
        if dual_v != coordinate_y:
            continue
        contraction = factorial(2 * order - dual_v) * factorial(dual_v)
        result[exponents] = (
            result.get(exponents, 0) + coefficient * contraction
        )
    return {exponents: value for exponents, value in result.items() if value}


def primitive_terms(terms: dict[tuple[int, ...], int]) -> dict[tuple[int, ...], int]:
    """Remove the positive integer content of a moment polynomial."""

    content = 0
    for coefficient in terms.values():
        content = gcd(content, abs(coefficient))
    assert content
    return {
        exponents: coefficient // content
        for exponents, coefficient in terms.items()
    }


def singular_expression(
    terms: dict[tuple[int, ...], int], support_size: int
) -> str:
    """Normalize coefficient zero to one and serialize for Singular."""

    if not terms:
        return "0"
    answer = ""
    for exponents, coefficient in sorted(primitive_terms(terms).items()):
        factors: list[str] = []
        for index, exponent in enumerate(exponents[1:], start=1):
            if exponent == 1:
                factors.append(f"c{index}")
            elif exponent > 1:
                factors.append(f"c{index}^{exponent}")
        monomial = "*".join(factors) or "1"
        if coefficient == 1:
            term = monomial
        elif coefficient == -1:
            term = f"-{monomial}"
        else:
            term = f"{coefficient}*{monomial}"
        answer += term if not answer or term.startswith("-") else f"+{term}"
    assert support_size == len(next(iter(terms)))
    return answer


def global_singular_expression(
    terms: dict[tuple[int, ...], int]
) -> str:
    """Serialize a homogeneous moment in all nine coefficient variables."""

    if not terms:
        return "0"
    answer = ""
    for exponents, coefficient in sorted(primitive_terms(terms).items()):
        factors: list[str] = []
        for index, exponent in enumerate(exponents):
            if exponent == 1:
                factors.append(f"x{index}")
            elif exponent > 1:
                factors.append(f"x{index}^{exponent}")
        monomial = "*".join(factors) or "1"
        if coefficient == 1:
            term = monomial
        elif coefficient == -1:
            term = f"-{monomial}"
        else:
            term = f"{coefficient}*{monomial}"
        answer += term if not answer or term.startswith("-") else f"+{term}"
    assert len(next(iter(terms))) == len(MONOMIALS)
    return answer


def support_label(support: tuple[int, ...]) -> list[str]:
    return [f"M_{MONOMIALS[index][0]}{MONOMIALS[index][1]}" for index in support]


def support_weights(support: tuple[int, ...]) -> list[int]:
    return [
        MONOMIALS[index][0] - MONOMIALS[index][1]
        for index in support
    ]


def census(
    singular: str, support_size: int, cutoff: int
) -> list[dict[str, object]]:
    """Run all exact-support charts of one size in a single Singular process."""

    supports = list(combinations(range(len(MONOMIALS)), support_size))
    coefficient_variables = [
        f"c{index}" for index in range(1, support_size)
    ]
    ring_variables = coefficient_variables + ["rho"]
    localization_product = "*".join(coefficient_variables) or "1"
    programs: list[str] = []
    for chart, support in enumerate(supports):
        moments = [
            singular_expression(moment_terms(support, order), support_size)
            for order in range(1, cutoff + 1)
        ]
        moments = [moment for moment in moments if moment != "0"]
        localization = f"rho*{localization_product}-1"
        programs.append(
            f"""
ring r_{support_size}_{chart}=0,({",".join(ring_variables)}),dp;
option(redSB);
ideal I={",".join(moments + [localization])};
ideal G=std(I);
print(
  "RESULT {support_size} {chart} "
  +string(reduce(1,G)==0)+" "+string(dim(G))
);
"""
        )

    completed = subprocess.run(
        [singular, "-q"],
        input="\n".join(programs),
        text=True,
        capture_output=True,
        check=True,
        timeout=180,
    )
    matches = re.findall(
        rf"(?m)^RESULT {support_size} (\d+) ([01]) (-?\d+)$",
        completed.stdout,
    )
    assert len(matches) == len(supports), completed.stderr[-4000:]
    survivors: list[dict[str, object]] = []
    for chart_text, unit_text, dimension_text in matches:
        if unit_text == "1":
            continue
        support = supports[int(chart_text)]
        survivors.append(
            {
                "indices": list(support),
                "monomials": support_label(support),
                "weights": support_weights(support),
                "localized_dimension": int(dimension_text),
            }
        )
    return survivors


def contraction(expression: sp.Expr) -> sp.Expr:
    """Apply E_2 to a bidegree-balanced polynomial."""

    W, V, Z, Y = sp.symbols("W V Z Y")
    result = sp.Integer(0)
    for (w_degree, v_degree, z_degree, y_degree), coefficient in sp.Poly(
        sp.expand(expression), W, V, Z, Y
    ).terms():
        if w_degree <= z_degree and v_degree <= y_degree:
            multiplier = (
                factorial(z_degree)
                // factorial(z_degree - w_degree)
                * factorial(y_degree)
                // factorial(y_degree - v_degree)
            )
            result += (
                coefficient
                * multiplier
                * Z ** (z_degree - w_degree)
                * Y ** (y_degree - v_degree)
            )
    return sp.factor(result)


def check_linear_compression() -> None:
    """Check the first two identities for the natural linear compression."""

    W, V, Z, Y = sp.symbols("W V Z Y")
    a, b, c, d = sp.symbols("a b c d")
    t = c * Z + d * Y
    tau = a * W + b * V
    candidate = sp.expand(tau * (t - Y) * (W * Z + V * t))
    obstruction = a * c + b * (d - 1)

    first = contraction(candidate)
    second = contraction(sp.expand(candidate**2))
    assert sp.expand(first - (2 * d + 1) * obstruction) == 0
    assert sp.expand(
        second
        - 4 * (6 * d**2 + 3 * d + 1) * obstruction**2
    ) == 0
    assert sp.expand((6 * d**2 + 3 * d + 1).subs(d, -sp.Rational(1, 2))) == 1

    # On the forced orthogonality branch, adapted pair coordinates put the
    # nonzero monomials in weights 1,2,1.
    assert min((1, 2, 1)) > 0


def support_symmetry_orbit(support: tuple[int, ...]) -> set[tuple[int, ...]]:
    """Orbit under transposition and simultaneous reversal of both pairs."""

    orbit = {support}
    changed = True
    while changed:
        changed = False
        for member in tuple(orbit):
            transformed = []
            rotated = []
            for index in member:
                i, j = MONOMIALS[index]
                transformed.append(MONOMIALS.index((j, i)))
                rotated.append(MONOMIALS.index((2 - i, 2 - j)))
            for image in (tuple(sorted(transformed)), tuple(sorted(rotated))):
                if image not in orbit:
                    orbit.add(image)
                    changed = True
    return orbit



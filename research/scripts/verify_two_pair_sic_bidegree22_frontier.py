"""Exact bidegree-(2,2) theorem for two-pair SIC.

Use contraction pairs (W,Z),(V,Y) and write

    M_ij = W^(2-i) V^i Z^(2-j) Y^j,  0 <= i,j <= 2.

The global calculation writes a general form as sum x_ij M_ij.  Singular
eliminates the four-parameter finite-flag one-sided normal form and obtains
a prime ideal J with twelve Groebner generators.  If I is generated by the
first six pure contractions, exact reductions prove I is contained in J,
the first generator of J lies in I, and the seventh power of each remaining
generator lies in I.  Hence radical(I)=J, proving the SIC conclusion for
every bidegree-(2,2) form, including all dense eight- and nine-term charts.

The earlier sparse audit is retained as an independent support-level
regression.  For every exact support of size at most seven, it normalizes
the first nonzero coefficient and localizes all remaining coefficients.
The eight six-term and twelve seven-term survivor charts have explicit
Laurent-curve radicals and hidden one-sided normal forms.

The script also checks the natural four-parameter linear compression of the
three-pair witness.  Its first two contractions force the orthogonality
branch, which the written proof puts into a strict one-sided normal form.

Moments through order eight leave twelve seven-term charts; four explicit
Laurent-curve radicals cover them by symmetry and again give hidden
one-sided normal forms.
"""


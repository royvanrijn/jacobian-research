#!/usr/bin/env python3
"""Exact all-orders nodal persistence of the non-Cartier Kahler different.

The exact graded gauge quotient for the nodal cubic symbol is

    ker(C) / im(G_nod) = Q[y,z](-3),

generated by the compatible tensor eta attached to Z^3.  Successive formal
gauge elimination therefore puts every compatible tensor with fixed nodal
leading symbol in the form

    h_nod + f(y,z) eta,       f in (y,z) Q[[y,z]].

This checker supplies the algebraic input needed to make the normal form an
all-orders different statement.  It computes the universal coefficient
family h_nod+u*eta, proves that its multiplication table is affine-linear in
u, computes its intrinsic different Nakayama module as Q[u]^6, and verifies
strict weighted-Rees presentations for Omega and coker(B -> Omega^3) when u
has collision weight one.

For a graph specialization u -> f in the collision ideal, the initial form
of u-f is monic in u on the central associated-graded packets.  It is
therefore regular on both packets.  The annihilator commutes with the graph
specialization, and J/nJ has dimension six.  The conclusion covers formal
compatible corrections to every order, but does not assert normality or the
existence of a Keller open.
"""


def canonical_sha256(value: Any) -> str:
    return hashlib.sha256(
        json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
        ).encode()
    ).hexdigest()


def table_record(
    table: dict[tuple[int, int], sp.Matrix | sp.Expr],
) -> dict[str, list[str] | str]:
    result: dict[str, list[str] | str] = {}
    for pair in sorted(table):
        key = f"{pair[0]}{pair[1]}"
        value = table[pair]
        if isinstance(value, sp.MatrixBase):
            result[key] = [sp.sstr(sp.factor(entry)) for entry in value]
        else:
            result[key] = sp.sstr(sp.factor(value))
    return result


def universal_nakayama_normal_form_difference(
    eta_tensor: dict[tuple[int, int, int], sp.Expr],
) -> int:
    """Compare the universal pruned J/nJ presentation with (x,y,z)^6."""

    program, _parameters = cubic.singular_subspace_program(
        cubic.CUBIC_STRATA["nodal"],
        (eta_tensor,),
    )
    expected_generators: list[list[sp.Expr]] = []
    for component in range(6):
        for variable in cubic.BASE_VARIABLES:
            generator = [sp.Integer(0)] * 6
            generator[component] = variable
            expected_generators.append(generator)
    program = program.replace(
        "quit;",
        "module expected_different_generator_presentation="
        + ",".join(map(cubic.singular_vector, expected_generators))
        + ";expected_different_generator_presentation=std("
        + "expected_different_generator_presentation);"
        + "module universal_minus_expected=simplify(reduce("
        + "pruned_different_generator_presentation,"
        + "expected_different_generator_presentation),2);"
        + "module expected_minus_universal=simplify(reduce("
        + "expected_different_generator_presentation,"
        + "pruned_different_generator_presentation),2);"
        + 'print("EXPECTED_DIFFERENT_PRESENTATION_DIFFERENCE="'
        + "+string(size(universal_minus_expected)"
        + "+size(expected_minus_universal)));"
        + "quit;",
    )
    singular = shutil.which("Singular")
    assert singular is not None, "Singular is required"
    completed = subprocess.run(
        [singular, "-q"],
        input=program,
        text=True,
        capture_output=True,
        check=True,
        timeout=1800,
    )
    prefix = "EXPECTED_DIFFERENT_PRESENTATION_DIFFERENCE="
    values = [
        int(line[len(prefix) :])
        for line in completed.stdout.splitlines()
        if line.startswith(prefix)
    ]
    assert len(values) == 1, completed.stdout + completed.stderr
    return values[0]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--refresh",
        action="store_true",
        help="intentionally replace the pinned generated artifact",
    )
    args = parser.parse_args()
    cubic.FACTOR_SINGULAR_EXPRESSIONS = False

    compatibility = smooth.compatibility_matrix()
    nodal_tensor = atlas.symbol_tensor(cubic.CUBIC_STRATA["nodal"])
    gauge = smooth.gauge_matrix(nodal_tensor)
    eta = atlas.symbol_tensor(cubic.Z**3)
    assert (
        compatibility * eta
    ).applyfunc(sp.expand) == sp.zeros(6, 1)

    module_certificate = singular_module_certificate(
        compatibility,
        gauge,
        eta,
    )
    expected_module_certificate = {
        "kernel_generator_count": 10,
        "generation_difference_size": 0,
        "annihilator_singular_syntax": "x",
        "hilbert_numerator_over_one_minus_t_cubed": [1, -1],
    }
    assert module_certificate == expected_module_certificate

    universal_coefficient = sp.Symbol("u")
    universal_tensor = {
        triple: sp.expand(universal_coefficient * eta[row])
        for row, triple in enumerate(smooth.TRIPLES)
    }
    central_trace_free, central_scalar = cubic.multiplication_table(
        cubic.CUBIC_STRATA["nodal"]
    )
    universal_trace_free, universal_scalar = cubic.multiplication_table(
        cubic.CUBIC_STRATA["nodal"], universal_tensor
    )
    trace_free_correction = {
        pair: (
            universal_trace_free[pair] - central_trace_free[pair]
        ).applyfunc(sp.expand)
        for pair in central_trace_free
    }
    scalar_correction = {
        pair: sp.expand(universal_scalar[pair] - central_scalar[pair])
        for pair in central_scalar
    }
    for correction in trace_free_correction.values():
        for entry in correction:
            assert sp.Poly(entry, universal_coefficient).degree() <= 1
            assert sp.expand(entry.subs(universal_coefficient, 0)) == 0
    for correction in scalar_correction.values():
        assert sp.Poly(correction, universal_coefficient).degree() <= 1
        assert sp.expand(
            correction.subs(universal_coefficient, 0)
        ) == 0
    assert any(
        entry != 0
        for correction in trace_free_correction.values()
        for entry in correction
    )
    assert any(correction != 0 for correction in scalar_correction.values())

    eta_tensor = {
        triple: sp.expand(eta[row])
        for row, triple in enumerate(smooth.TRIPLES)
    }
    universal_family = cubic.run_singular_subspace_certificate(
        cubic.CUBIC_STRATA["nodal"],
        (eta_tensor,),
        timeout=1800,
    )
    expected_universal_family = {
        "parameter_count": 1,
        "cotangent_saturation_generators": 0,
        "support_module_dimension": 3,
        "support_ext3_vector_dimension": 0,
        "support_ext2_dimension": 1,
        "support_ext2_multiplicity": 6,
        "support_ext2_parameter_axis_radical_difference": 0,
        "support_ext2_central_pruned_presentation_difference": 0,
        "support_ext2_pruned_presentation_rank": 3,
        "support_ext2_collision_square_action_generators": 0,
        "different_generator_module_dimension": 1,
        "different_generator_module_multiplicity": 6,
        "different_generator_parameter_axis_radical_difference": 0,
        "different_generator_central_pruned_presentation_difference": 0,
        "different_generator_pruned_presentation_rank": 6,
    }
    assert universal_family == expected_universal_family
    expected_presentation_difference = (
        universal_nakayama_normal_form_difference(eta_tensor)
    )
    assert expected_presentation_difference == 0

    weighted_rees = cubic.run_singular_rees_base_change_certificate(
        cubic.CUBIC_STRATA["nodal"],
        (eta_tensor,),
        timeout=1800,
        parameter_collision_weights=(1,),
    )
    expected_weighted_rees = {
        "parameter_count": 1,
        "cotangent_rees_torsion_generators": 0,
        "cotangent_initial_presentation_difference": 0,
        "annihilator_cokernel_rees_torsion_generators": 0,
        "annihilator_cokernel_initial_presentation_difference": 0,
    }
    assert weighted_rees == expected_weighted_rees

    trace_free_record = table_record(trace_free_correction)
    scalar_record = table_record(scalar_correction)
    exact_data = {
        "module_certificate": module_certificate,
        "eta_components": [sp.sstr(entry) for entry in eta],
        "affine_trace_free_correction": trace_free_record,
        "affine_scalar_correction": scalar_record,
        "universal_coefficient_family": universal_family,
        "expected_nakayama_presentation_difference": (
            expected_presentation_difference
        ),
        "weighted_rees_certificate": weighted_rees,
    }
    artifact = {
        "schema": "nodal-all-orders-different-persistence.v1",
        "case": "complete-formal-nodal-normal-slice",
        "mathematical_scope": (
            "Exact characteristic-zero theorem for every compatible formal "
            "tensor with fixed nodal cubic symbol. The exact graded gauge "
            "cokernel is Q[y,z](-3), so recursive filtered gauge elimination "
            "gives h_nod+f(y,z)*eta with f in (y,z)Q[[y,z]]. The universal "
            "coefficient multiplication is affine-linear, its intrinsic "
            "different Nakayama module is Q[u]^6, and weight-one strict "
            "Rees packets make u-f regular under every graph specialization. "
            "Hence the intrinsic Kahler different has six minimal local "
            "generators and is non-Cartier to all formal orders. Normality, "
            "algebraization of an arbitrary formal gauge, and Keller-open "
            "compatibility are not asserted."
        ),
        "normal_form": {
            "gauge_cokernel": "Q[y,z](-3)",
            "generator": "eta(Z^3)",
            "coefficient_ring": "Q[[y,z]]",
            "coefficient_ideal": "(y,z)",
            "tensor": "h_nod+f(y,z)*eta",
        },
        "graph_specialization_lemma": {
            "universal_ring": "Q[u,x,y,z]",
            "weights": {"u": 1, "x": 1, "y": 1, "z": 1},
            "specialization": "u -> f, ord_(x,y,z)(f)>=1",
            "regularity_reason": (
                "in(u-f) is monic in u on each central associated-graded "
                "packet, which is obtained from the central packet by "
                "polynomial extension in u"
            ),
            "consequence": (
                "Tor_1 vanishes for the annihilator-control cokernel, so "
                "Ann(Omega) commutes with the graph specialization"
            ),
        },
        "exact_data": exact_data,
        "exact_data_sha256": canonical_sha256(exact_data),
        "proved": [
            (
                "every compatible formal nodal tensor has a recursive "
                "normal form h_nod+f(y,z)*eta"
            ),
            (
                "the universal normal coefficient changes multiplication "
                "only affine-linearly"
            ),
            (
                "the cotangent and annihilator-control Rees packets are "
                "strict with literal central initial presentations"
            ),
            (
                "after every polynomial or formal graph specialization, "
                "the intrinsic Kahler different has six minimal generators"
            ),
            (
                "the Kahler different is non-Cartier for every compatible "
                "formal correction with fixed nodal leading symbol"
            ),
        ],
        "not_proved": [
            "normality of the normal-form algebra",
            "algebraization of the infinite formal gauge transformation",
            "existence or compatibility of a Keller open",
            "the analogous all-orders statement for the other five singular-squarefree symbols",
        ],
        "reproduce": (
            ".venv/bin/python "
            "scripts/verify_nodal_all_orders_different_persistence.py"
        ),
    }
    if args.refresh:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(
            json.dumps(artifact, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
    else:
        pinned = json.loads(OUTPUT.read_text(encoding="utf-8"))
        assert artifact == pinned, "stale nodal all-orders artifact"

    print("PASS: nodal gauge cokernel is Q[y,z](-3)")
    print("PASS: universal nodal multiplication is affine-linear in u")
    print("PASS: universal intrinsic J/nJ is Q[u]^6")
    print("PASS: weight-one Rees packets are strict with central initial form")
    print("PASS: every formal graph u=f has six-generator non-Cartier different")
    action = "wrote" if args.refresh else "replayed"
    print(f"PASS: {action} {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

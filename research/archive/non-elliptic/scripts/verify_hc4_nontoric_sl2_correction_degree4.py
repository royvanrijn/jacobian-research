#!/usr/bin/env python3
"""Exclude degree-at-most-four non-toric SL(2) corrections in the HC(5) descent.

The foundational six-variable Meng doubling has a nonconstant polynomial
unit pivot: the coefficient row of the affine source variable z is
unimodular.  Its explicit completion gives the five-variable Meng--Yang
potential.  After the next unit-pivot descent, every relative polynomial
change of the two complementary dual variables by

    C(x,y) in SL(2, QQ[x,y])

produces a four-variable potential

    psi = f(x,y) + 2*G1(x,y)*r + 2*G2(x,y)*s,
    G = beta*C,

where

    beta = (-y*P(x*y), x*Q(x*y)).

The Hessian determinant is 16*det(DG)^2.  A surviving Meng collision must
also satisfy G(1,-3/2)=G(-1,3/2).

This checker takes all four entries of C to be arbitrary polynomials of
total degree at most four (60 coefficients).  It forms the exact ideal
generated by:

* every coefficient of det(C)-1;
* every nonconstant coefficient of det(DG).

Singular over QQ computes the reduced obstruction ideal as the unit ideal.
Thus no correction in this bounded non-toric class can even have constant
nonzero Hessian determinant; the collision equations are not needed.

The checker also starts from the explicit degree-ten toric correction,
whose coefficient map is (y,2x), and appends an arbitrary affine SL(2)
matrix.  In that perturbative class, the determinant-one, constant-Jacobian,
and collision equations again generate the unit ideal.
"""

from __future__ import annotations

import shutil
import subprocess

import sympy as sp


SINGULAR = shutil.which("Singular")
if SINGULAR is None:
    raise SystemExit("ERROR: Singular is required for this exact checker")


x, y = sp.symbols("x y")
v = x * y
radial_P = 18 * v**5 + 81 * v**4 + 120 * v**3 + 60 * v**2 - 1
radial_Q = (v + 1) * (v + 2)
beta = sp.Matrix([[-y * radial_P, x * radial_Q]])


# Universal doubled-map determinant identity.  The upper-left Hessian block
# is irrelevant: for a potential f+2*G1*r+2*G2*s the determinant is the
# square of the off-diagonal two-by-two Jacobian block.
h11, h12, h22 = sp.symbols("h11 h12 h22")
j11, j12, j21, j22 = sp.symbols("j11 j12 j21 j22")
generic_hessian = sp.Matrix(
    [
        [h11, h12, 2 * j11, 2 * j21],
        [h12, h22, 2 * j12, 2 * j22],
        [2 * j11, 2 * j12, 0, 0],
        [2 * j21, 2 * j22, 0, 0],
    ]
)
assert sp.expand(
    generic_hessian.det()
    - 16 * (j11 * j22 - j12 * j21) ** 2
) == 0


degree_bound = 4
monomials = tuple(
    x**x_degree * y ** (total_degree - x_degree)
    for total_degree in range(degree_bound + 1)
    for x_degree in range(total_degree, -1, -1)
)
assert len(monomials) == 15

coefficient_groups: list[tuple[sp.Symbol, ...]] = []
coefficient_names: list[str] = []
entries: list[sp.Expr] = []
for letter in "abcd":
    group = sp.symbols(
        " ".join(f"{letter}{index}" for index in range(len(monomials)))
    )
    coefficient_groups.append(group)
    coefficient_names.extend(str(symbol) for symbol in group)
    entries.append(
        sum(
            coefficient_value * monomial
            for coefficient_value, monomial in zip(
                group,
                monomials,
                strict=True,
            )
        )
    )

a, b, c, d = entries
correction = sp.Matrix([[a, b], [c, d]])
corrected_map = beta * correction
G1 = sp.expand(corrected_map[0, 0])
G2 = sp.expand(corrected_map[0, 1])
corrected_jacobian = sp.expand(
    sp.Matrix([G1, G2]).jacobian((x, y)).det()
)


def spatial_coefficients(
    expression: sp.Expr,
    *,
    omit_constant: bool = False,
) -> list[sp.Expr]:
    return [
        coefficient_value
        for monomial, coefficient_value in sp.Poly(
            sp.expand(expression),
            x,
            y,
        ).terms()
        if not (omit_constant and monomial == (0, 0))
    ]


equations = spatial_coefficients(correction.det() - 1)
equations.extend(
    spatial_coefficients(corrected_jacobian, omit_constant=True)
)

collision_plus = {x: 1, y: -sp.Rational(3, 2)}
collision_minus = {x: -1, y: sp.Rational(3, 2)}

assert len(coefficient_names) == 60
assert len(equations) == 263


def clear_denominator(expression: sp.Expr) -> sp.Expr:
    symbols = tuple(sorted(expression.free_symbols, key=str))
    polynomial = sp.Poly(expression, *symbols) if symbols else sp.Poly(expression)
    return sp.expand(polynomial.clear_denoms()[1].as_expr())


singular_equations = [clear_denominator(equation) for equation in equations]
singular_source = "\n".join(
    [
        f"ring r=0,({','.join(coefficient_names)}),dp;",
        "ideal I="
        + ",".join(
            str(equation).replace("**", "^")
            for equation in singular_equations
        )
        + ";",
        "ideal G=std(I);",
        '"PARAMETERS",nvars(basering);',
        '"EQUATIONS",size(I);',
        '"BASIS_SIZE",size(G);',
        '"REDUCED_ONE",reduce(1,G);',
    ]
)

result = subprocess.run(
    [SINGULAR, "-q"],
    input=singular_source,
    text=True,
    capture_output=True,
    check=False,
)
if result.returncode != 0:
    raise AssertionError(
        "Singular failed:\n" + result.stdout + "\n" + result.stderr
    )
output = result.stdout
assert "PARAMETERS 60" in output
assert "EQUATIONS 263" in output
assert "BASIS_SIZE 1" in output
assert "REDUCED_ONE 0" in output


def affine_polynomial(prefix: str) -> tuple[sp.Expr, tuple[sp.Symbol, ...]]:
    coefficients = sp.symbols(f"{prefix}0 {prefix}x {prefix}y")
    return (
        coefficients[0] + coefficients[1] * x + coefficients[2] * y,
        coefficients,
    )


# Perturb the known toric correction.  Its corrected coefficient map is
# exactly (y,2x), already of constant Jacobian.  An arbitrary affine
# determinant-one matrix is the full factorization-independent affine
# perturbation class.
affine_entries = [affine_polynomial(letter) for letter in "ABCD"]
affine_symbols = tuple(
    symbol
    for _, coefficient_tuple in affine_entries
    for symbol in coefficient_tuple
)
affine_matrix = sp.Matrix(
    [
        [affine_entries[0][0], affine_entries[1][0]],
        [affine_entries[2][0], affine_entries[3][0]],
    ]
)
affine_map = sp.Matrix([[y, 2 * x]]) * affine_matrix
affine_G1 = sp.expand(affine_map[0, 0])
affine_G2 = sp.expand(affine_map[0, 1])
affine_jacobian = sp.expand(
    sp.Matrix([affine_G1, affine_G2]).jacobian((x, y)).det()
)
affine_equations = spatial_coefficients(affine_matrix.det() - 1)
affine_equations.extend(
    spatial_coefficients(affine_jacobian, omit_constant=True)
)
affine_equations.extend(
    [
        sp.factor(
            affine_G1.subs(collision_plus)
            - affine_G1.subs(collision_minus)
        ),
        sp.factor(
            affine_G2.subs(collision_plus)
            - affine_G2.subs(collision_minus)
        ),
    ]
)
assert len(affine_symbols) == 12
assert len(affine_equations) == 13
affine_basis = sp.groebner(
    affine_equations,
    *affine_symbols,
    order="grevlex",
)
assert affine_basis.contains(sp.Integer(1))


print("PASS: the four-variable determinant is 16*det(DG)^2")
print("PASS: the full degree-at-most-four correction has 60 parameters")
print("PASS: determinant and constant-Jacobian give 263 exact equations")
print("PASS: Singular over QQ reduces their ideal to the unit ideal")
print("PASS: no degree-at-most-four non-toric SL(2) correction survives")
print("PASS: no affine SL(2) perturbation of the toric correction survives")

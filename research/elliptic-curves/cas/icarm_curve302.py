def weierstrass_invariants() -> tuple[int, int, int, int, int, int, int]:
    """Return ``b2,b4,b6,b8,c4,c6,Delta`` for the public model."""

    a1, a2, a3, a4, a6 = GENERAL_WEIERSTRASS_COEFFICIENTS
    b2 = a1 * a1 + 4 * a2
    b4 = 2 * a4 + a1 * a3
    b6 = a3 * a3 + 4 * a6
    b8 = a1 * a1 * a6 + 4 * a2 * a6 - a1 * a3 * a4 + a2 * a3 * a3 - a4 * a4
    c4 = b2 * b2 - 24 * b4
    c6 = -b2**3 + 36 * b2 * b4 - 216 * b6
    discriminant = -b2 * b2 * b8 - 8 * b4**3 - 27 * b6**2 + 9 * b2 * b4 * b6
    return tuple(int(value) for value in (b2, b4, b6, b8, c4, c6, discriminant))


def on_curve(point: tuple[Fraction, Fraction]) -> bool:
    x, y = (Q(value) for value in point)
    a1, a2, a3, a4, a6 = GENERAL_WEIERSTRASS_COEFFICIENTS
    return y * y + a1 * x * y + a3 * y == x**3 + a2 * x * x + a4 * x + a6


def short_coefficients() -> tuple[Fraction, ...]:
    _, _, _, _, c4, c6, _ = weierstrass_invariants()
    return Q(0), Q(0), Q(0), Q(-27 * c4), Q(-54 * c6)


def to_short(point: tuple[Fraction, Fraction]) -> tuple[Fraction, Fraction]:
    x, y = (Q(value) for value in point)
    return 36 * x + 15, 108 * (2 * y + x + 1)


def on_short_curve(point: tuple[Fraction, Fraction]) -> bool:
    x, y = (Q(value) for value in point)
    _, _, _, a4, a6 = short_coefficients()
    return y * y == x**3 + a4 * x + a6



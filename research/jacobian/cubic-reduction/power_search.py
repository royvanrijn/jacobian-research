#!/usr/bin/env python3
"""Finite exact shared-cube support search, beyond termwise polarization choices."""
from pathlib import Path
from fractions import Fraction as Q
import hashlib,json,sys,time
import sympy as sp
from flint import fmpq_mat
import z3
HERE=Path(__file__).resolve().parent
DB=HERE.parent/"de-bondt-2610.24889"
sys.path.insert(0,str(DB))
# The existing modules use a local absolute import named verify.
sys.modules.pop("verify",None)
from polarize import terms,decomposition,linear
from verify import cubic12,homogeneous18,X
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def zr(q):return z3.RealVal(str(q))
def main():
    out=HERE/"power-search";out.mkdir(exist_ok=True)
    provenance=json.loads((DB/"receipt.json").read_text())
    for name in ["verify.py","polarize.py","polarization.json"]:assert sha(DB/name)==provenance["sha256"][name]
    old=json.loads((DB/"polarization.json").read_text());oldforms=list(map(tuple,old["forms"]));allforms=set()
    for _,_,factors in terms(True):
        for mode in range(5):allforms.update(decomposition(factors,mode))
    assert set(oldforms)<=allforms
    forms=oldforms+sorted(allforms-set(oldforms));m=len(forms)
    cubes=[dict(sp.Poly(linear(f)**3,*X).terms()) for f in forms]
    _,K,_=cubic12(2);H,_=homogeneous18(K);H[-1]=X[-1]**3
    target=[dict(sp.Poly(f,*X).terms()) for f in H]
    mons=sorted(set().union(*(set(c) for c in cubes),*(set(t) for t in target)))
    C=fmpq_mat([[str(c.get(e,0)) for c in cubes] for e in mons])
    T=fmpq_mat([[str(t.get(e,0)) for t in target] for e in mons])
    cr,rank=C.rref();basis=[next(j for j in range(m) if cr[i,j]) for i in range(rank)]
    assert basis[:90]==list(range(90))
    joint=fmpq_mat([[str(C[i,j]) for j in basis]+[str(C[i,j]) for j in range(m)]+[str(T[i,j]) for j in range(18)] for i in range(len(mons))])
    rr,jrank=joint.rref();assert jrank==rank
    A=[[Q(str(rr[i,rank+j])) for j in range(m)] for i in range(rank)]
    B=[[Q(str(rr[i,rank+m+j])) for j in range(18)] for i in range(rank)]
    assert sum(any(row) for row in B)==90
    nonbasis=[j for j in range(m) if j not in basis]
    null=[{} for _ in range(m)]
    for k,j in enumerate(nonbasis):
        null[j][k]=Q(1)
        for i,b in enumerate(basis):
            if A[i][j]:null[b][k]=-A[i][j]
    initial=[[Q(0)]*18 for _ in range(m)]
    for i,b in enumerate(basis):initial[b]=B[i]
    padding=next(i for i,f in enumerate(forms) if f==(0,)*17+(1,))
    assert [initial[i][17] for i in range(m)]==[Q(i==padding) for i in range(m)]
    solver=z3.Solver();solver.set(timeout=60000)
    parameters=[[z3.Real("n_%d_%d"%(k,o)) for o in range(17)] for k in range(len(nonbasis))]
    active=[z3.Bool("active_%d"%i) for i in range(m)]
    expressions=[]
    for i in range(m):
        row=[zr(initial[i][o])+z3.Sum([zr(c)*parameters[k][o] for k,c in null[i].items()]) for o in range(17)]
        expressions.append(row)
        solver.add(z3.Implies(z3.Not(active[i]),z3.And([e==0 for e in row])))
    solver.add(active[padding],z3.PbLe([(a,1) for a in active],89))
    receipt=dict(status="running",source_sha256=sha(Path(__file__)),inputs={name:sha(DB/name) for name in ["verify.py","polarize.py","polarization.json"]},
       candidate_forms=m,rank=rank,nullity=len(nonbasis),baseline=90,bound=89,timeout_ms=60000,
       scope="Finite178-form space generated by all five polarization identities on the existing grouped18-variable tensor. No global lower bound.")
    (out/"checkpoint.json").write_text(json.dumps(receipt,indent=2,sort_keys=True)+"\n")
    print(json.dumps(receipt),flush=True);t=time.monotonic();answer=solver.check()
    receipt.update(status=str(answer),solver_seconds=round(time.monotonic()-t,3),solver_version=z3.get_version_string())
    if answer==z3.sat:
        model=solver.model();coefficients=[]
        for i,row in enumerate(expressions):
            values=[]
            for expr in row:
                value=model.eval(expr,model_completion=True);assert z3.is_rational_value(value)
                values.append(Q(value.numerator_as_long(),value.denominator_as_long()))
            coefficients.append(values+[Q(i==padding)])
        selected=[i for i,row in enumerate(coefficients) if any(row)]
        assert len(selected)<=89 and padding in selected
        mat=fmpq_mat([[str(coefficients[i][o]) for o in range(18)] for i in selected])
        selectedC=fmpq_mat([[str(C[a,i]) for i in selected] for a in range(C.nrows())])
        assert selectedC*mat==T
        candidate=dict(source_sha256=sha(Path(__file__)),forms=[forms[i] for i in selected],
            B=[[str(coefficients[i][o]) for i in selected] for o in range(18)],
            size=len(selected),padding_index=selected.index(padding),baseline=90,
            scope="Exact cube-identity candidate; a smaller cubic-linear Keller lift is not claimed until its determinant and collision are built and independently checked.")
        (out/"candidate.json").write_text(json.dumps(candidate,indent=2,sort_keys=True)+"\n")
        receipt["candidate_size"]=len(selected)
    elif answer==z3.unknown:receipt["reason"]=solver.reason_unknown()
    (out/"checkpoint.json").write_text(json.dumps(receipt,indent=2,sort_keys=True)+"\n")
    print(json.dumps(receipt),flush=True)
if __name__=="__main__":main()


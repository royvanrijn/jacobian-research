def verify_matching_cutoff(left, right, cutoff, knots, divisions):
    require(len(knots) == divisions + 1 and any(
        (left, right, Q(cutoff, 8)) == row[:3] for row in FIXED_CASES
    ), ("known cutoff", left, right, cutoff))
    for rays in knots:
        levels = (RAY_SCALE, *rays, -RAY_SCALE)
        require(len(rays) == 10 and all(a > b for a, b in zip(levels, levels[1:])),
                "ordered rays")


def verify_row_loss():
    count = 0
    for endpoint, factor in LOSS_FACTORS:
        limit = Q(endpoint, 8)
        lower_cap = int(limit * factor / (factor - 1)**2)
        gap_stop = 1
        while Q(gap_stop**2, lower_cap + gap_stop) <= limit:
            gap_stop += 1
        for lower in range(1, lower_cap + 1):
            for gap in range(1, gap_stop):
                strength = Q(gap**2, lower + gap)
                if strength > limit or Q(gap, lower) <= factor - 1:
                    continue
                for order in ORDERS:
                    first = factorial(order * lower)
                    last = factorial(order * (lower + gap))
                    for k in range(1, order):
                        power = Q(first**(order-k) * last**k, factorial(order*lower+k*gap)**order)
                        exponent = factor * strength * k * (order-k) / 2
                        require(power <= exponential_lower(exponent),
                                ("row loss", limit, lower, gap, order, k))
                        count += 1
    return count


def verify_private_anchor(order, core, points, rays):
    upper = tuple((Q(a, 10000), Q(b, 10000)) for a, b in points if b > 0)
    real = tuple((Q(a, 10000), Q(0)) for a, b in points if b == 0)
    require(len(upper) == order//2 and len(real) == order%2
            and all(a < -DISK_RADIUS for a, b in real), ("anchor root counts", order))
    disks = upper + tuple((a, -b) for a, b in upper) + real
    for i, (a, b) in enumerate(disks):
        verify_disk(core, (a, b))
        require(all((a-c)**2 + (b-d)**2 > (2*DISK_RADIUS)**2
                    for c, d in disks[:i]), ("disjoint anchor disks", order))
    for (a, b), sector in zip(upper, range(int(order == 11), 11, 2), strict=True):
        require(b > DISK_RADIUS, ("above real line", order))
        for i, ray in enumerate(rays):
            c = Q(ray, RAY_SCALE)
            lo, hi = multiply_interval(root_bounds(1-c*c, 2), (-a, -a))
            if i < sector:
                require(c*b+lo > DISK_RADIUS, ("anchor ray side", order, i))
            else:
                require(c*b+hi < -DISK_RADIUS, ("anchor ray side", order, i))


def verify_low(left, right, cutoff, knots, anchors, expected):
    verify_matching_cutoff(left, right, cutoff, knots, cutoff)
    total = 0
    for order, points in zip(ORDERS, anchors, strict=True):
        core = private_core(order, left, right)
        verify_annulus(core, order)
        verify_private_anchor(order, core, points, knots[0])
        for i, (rays, next_rays) in enumerate(zip(knots, knots[1:])):
            factor = next(factor for last, factor in LOSS_FACTORS if i+1 <= last)

            def box(a, b):
                return coefficient_box(order, core, factor, (a, b))

            for ray, next_ray in zip(rays, next_rays, strict=True):
                total += replay_band(order, box, Q(i, 8), Q(i+1, 8), ray, next_ray, 11)
    require(total == expected, ("curvature cell count", left, right, total))
    return total


def possible_rows(curvature_limit):
    gap_bound = int(curvature_limit*(1+1/(11*FLOOR)))
    for gap in range(1, gap_bound+1):
        lower_bound = int(gap/(11*FLOOR)-Q(1, 11))
        for lower in range(1, lower_bound+1):
            reciprocal = Q(gap, 11*lower+1)
            if Q(gap**2, lower+gap) > curvature_limit or reciprocal <= FLOOR:
                continue
            square = prod(Q(11*lower+h, 11*lower+10*gap+h) for h in range(1, gap+1))
            yield reciprocal, Q(gap, 12*lower+1), square



def check_ordered(rays):
    levels = (RAY_SCALE, *rays, -RAY_SCALE)
    require(len(rays) == 8 and all(a > b for a, b in zip(levels, levels[1:])), "ordered rays")


def verify_binomial_anchor(rays):
    check_ordered(rays)
    cosines = (Q(1), *(Q(v, RAY_SCALE) for v in rays), Q(-1))
    for order in ORDERS:
        for index, x0 in enumerate(cosines):
            roots_before = (index + (order == 10)) // 2
            require((-1)**roots_before * anchor_value(order, x0) > 0, ("binomial anchor", order, index))


def verify_high():
    total = 0
    for left, right, threshold, rays, expected in HIGH:
        verify_binomial_anchor(rays)
        strength = Q(*threshold)
        count = 0
        for order in ORDERS:
            if left or right:
                maxima = coefficient_bounds(order, left, strength, right)
            else:
                require(strength == TOTAL_CUTOFF, "total cutoff")
                maxima = total_curvature_caps(order, strength)
            box = [(v, v) if k in (0, order) else (Q(0), v) for k, v in enumerate(maxima)]
            verify_annulus(box, order)
            for value in rays:
                cosine = Q(value, RAY_SCALE)
                cells = radial_replay(order, box, (cosine, cosine))
                require(cells is not None, ("high ray", left, right, order, cosine))
                count += cells
        require(count == expected, ("high-ray count", left, right, strength, count))
        total += count
    return total


def verify_row_loss():
    count = 0
    for endpoint, factor in LOSS:
        limit = Q(endpoint, 8)
        lower_cap = int(limit * factor / (factor - 1)**2)
        gap_stop = 1
        while Q(gap_stop**2, lower_cap + gap_stop) <= limit:
            gap_stop += 1
        for lower in range(1, lower_cap + 1):
            for gap in range(1, gap_stop):
                strength = Q(gap**2, lower + gap)
                if strength > limit or Q(gap, lower) <= factor - 1:
                    continue
                for order in ORDERS:
                    first = factorial(order * lower)
                    last = factorial(order * (lower + gap))
                    for k in range(1, order):
                        power = Q(first**(order-k) * last**k, factorial(order*lower+k*gap)**order)
                        exponent = factor * strength * k * (order-k) / 2
                        require(power <= exponential_lower(exponent),
                                ("row loss", limit, lower, gap, order, k))
                        count += 1
    return count


def verify_private_anchor(order, core, points, rays):
    upper = tuple((Q(a, 10000), Q(b, 10000)) for a, b in points if b > 0)
    real = tuple((Q(a, 10000), Q(0)) for a, b in points if b == 0)
    require(len(upper) == order//2 and len(real) == order%2
            and all(a < -DISK_RADIUS for a, b in real), ("anchor root counts", order))
    disks = upper + tuple((a, -b) for a, b in upper) + real
    for i, (a, b) in enumerate(disks):
        verify_disk(core, (a, b))
        require(all((a-c)**2 + (b-d)**2 > (2*DISK_RADIUS)**2
                    for c, d in disks[:i]), ("disjoint anchor disks", order))
    for (a, b), sector in zip(upper, range(int(order == 9), 9, 2), strict=True):
        require(b > DISK_RADIUS, ("above real line", order))
        for i, ray in enumerate(rays):
            c = Q(ray, RAY_SCALE)
            lo, hi = multiply_interval(root_bounds(1-c*c, 2), (-a, -a))
            if i < sector:
                require(c*b+lo > DISK_RADIUS, ("anchor ray side", order, i))
            else:
                require(c*b+hi < -DISK_RADIUS, ("anchor ray side", order, i))


def replay_band(order, make_box, first, last, left, right, depth_limit):
    def cosine(v):
        return Q(left, RAY_SCALE) + Q(right-left, RAY_SCALE)*(v-first)/(last-first)

    pending = [(first, last, 0)]
    count = 0
    while pending:
        a, b, depth = pending.pop()
        box = make_box(a, b)
        cells = radial_replay(order, box, tuple(sorted((cosine(a), cosine(b)))))
        if cells is not None:
            count += cells
            continue
        require(depth < depth_limit, ("unresolved moving ray", order, a, b, left, right))
        midpoint = (a+b)/2
        pending.extend(((a, midpoint, depth+1), (midpoint, b, depth+1)))
    return count


def verify_low(left, right, cutoff, knots, anchors):
    require(len(knots) == cutoff + 1 and any(
        (left, right, Q(cutoff, 8)) == (*row[:2], Q(*row[2]))
        for row in HIGH
    ), ("known cutoff", left, right, cutoff))
    for rays in knots:
        check_ordered(rays)
    total = 0
    for order, points in zip(ORDERS, anchors, strict=True):
        core = private_core(order, left, right)
        verify_annulus(core, order)
        verify_private_anchor(order, core, points, knots[0])
        for i, (rays, next_rays) in enumerate(zip(knots, knots[1:])):
            factor = next(factor for last, factor in LOSS if i+1 <= last)

            def box(a, b):
                return coefficient_box(order, core, factor, (a, b))

            for ray, next_ray in zip(rays, next_rays, strict=True):
                total += replay_band(order, box, Q(i, 8), Q(i+1, 8), ray, next_ray, 11)
    return total


def possible_rows(curvature_limit):
    gap_bound = int(curvature_limit*(1+1/(9*FLOOR)))
    for gap in range(1, gap_bound+1):
        lower_bound = int(gap/(9*FLOOR)-Q(1, 9))
        for lower in range(1, lower_bound+1):
            reciprocal = Q(gap, 9*lower+1)
            if Q(gap**2, lower+gap) > curvature_limit or reciprocal <= FLOOR:
                continue
            square = prod(Q(9*lower+h, 9*lower+8*gap+h) for h in range(1, gap+1))
            yield reciprocal, Q(gap, 10*lower+1), square


@lru_cache(maxsize=None)
def reciprocal_caps(rows, outer_lower):
    cap9, cap10 = FLOOR, 9*FLOOR/(10-FLOOR)
    for a, b, square in rows:
        if outer_lower**2 <= square:
            cap9, cap10 = max(cap9, a), max(cap10, b)
    return cap9, cap10


@lru_cache(maxsize=None)
def exponent_bounds(cap9, cap10):
    denominator_lo, denominator_hi = log_bounds(1+8*cap9)
    ratio = (
        log_bounds(1+Q(81, 10)*cap9)[0]/denominator_hi,
        1+log_bounds(1/(1-cap9/10))[1]/denominator_lo,
    )
    require(ratio[0] <= REFERENCE_RATIO <= ratio[1], ("outer-mean ratio", cap9))
    result = {}
    for order, cap, rho in ((9, cap9, (Q(1), Q(1))), (10, cap10, ratio)):
        m = order-1
        lo, hi = log_bounds(1+m*cap)
        exponents = []
        for k in range(1, order):
            distance = min(k, order-k)
            mean_lower = sum(log_bounds((1+(m-h)*cap)/(1+h*cap))[0] for h in range(distance))/hi
            skew_upper = 2*weighted_log_bounds(skew_weights(order, distance), cap)[1]/lo
            gaussian = Q(k*(order-k), m)
            e = gaussian * (1 if order == 9 else REFERENCE_RATIO)
            interval = rounded_interval(rho[0]*(mean_lower-skew_upper), rho[1]*(gaussian+skew_upper))
            require(0 < interval[0] <= e <= interval[1], ("Gaussian in coefficient envelope", order, k))
            exponents.append(interval)
        result[order] = tuple(exponents)
    return result


def verify_skew():
    count = 0
    for order in ORDERS:
        for distance in range(1, (order+1)//2):
            first = sum(w*h/(1+h*x) for h, w in enumerate(skew_weights(order, distance)))
            scale = 1+(order-1)*x
            second = scale*(scale*first).diff(x)
            check_nonnegative_on_interval(second.subs(x, x/2))
            count += 1
    return count


def verify_outer(left, right, cutoff, knots):
    require(len(knots) == OUTER_DIVISIONS + 1 and any(
        (left, right, Q(cutoff, 8)) == (*row[:2], Q(*row[2])) for row in HIGH
    ), ("known cutoff", left, right, cutoff))
    for rays in knots:
        check_ordered(rays)
    verify_binomial_anchor(knots[0])
    rows = tuple(possible_rows(Q(cutoff, 8)))
    require(all(0 < b <= a <= 1 for a, b, c in rows), "skew range")
    total = 0
    for order in ORDERS:
        core = private_core(order, left, right)
        verify_annulus(core, order)

        def box(a, b):
            exponents = exponent_bounds(*reciprocal_caps(rows, a))[order]
            values = [multiply_interval(c, (power_bounds(a, hi)[0], power_bounds(b, lo)[1]))
                      for c, (lo, hi) in zip(core[1:-1], exponents, strict=True)]
            return [(Q(1), Q(1)), *values, (Q(1), Q(1))]

        for i, (rays, next_rays) in enumerate(zip(knots, knots[1:])):
            for ray, next_ray in zip(rays, next_rays, strict=True):
                total += replay_band(order, box, Q(i, OUTER_DIVISIONS), Q(i+1, OUTER_DIVISIONS),
                                     ray, next_ray, 9)
    return total, len(rows)



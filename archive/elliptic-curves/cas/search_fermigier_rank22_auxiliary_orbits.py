#!/usr/bin/env python3
"""Search Fermigier accidental directions through their auxiliary Jacobians.

The published rank-22 specialization supplies eleven non-generic quartic
points.  For each point and each slope ``m in {-1,+1}``, substitution

    X = m*T+n

in the Fermigier quartic produces a pointed genus-one quartic in ``T``.  The
earlier searches enumerated rational points in direct height boxes.  This
script instead maps all twenty-two pointed quartics to auxiliary elliptic
curves, constructs the subgroup generated by their intersections with the
thirteen generic sections, saturates it through 20, and enumerates a bounded
coefficient ball in that group.  This reaches parameter heights far outside
the direct boxes without claiming that the auxiliary Mordell--Weil groups are
known completely.

Every inverse image is checked exactly on both the auxiliary slice and the
specialized Fermigier quartic.  The even symmetry ``T -> -T``, all generic
intersections, and a pinned 590-parameter prior manifest are removed.  A
small-prime radical upper proxy and an independent good-prime score choose a
bounded exact-conductor tranche.  Only completed conductors below 182.72 are
sent to point/rank triage, and an exact finite-reduction certificate is
attempted immediately if the numerical rank reaches 21.

This remains a bounded search.  Numerical height ranks and radical proxies
are selection evidence, not rank or conductor theorems.
"""


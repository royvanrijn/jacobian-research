def file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def projective_height(value: Fraction) -> int:
    value = Q(value)
    return max(abs(value.numerator), value.denominator)


def polynomial_value(
    coefficients: Sequence[Fraction], value: Fraction
) -> Fraction:
    answer = Q(0)
    for coefficient in reversed(coefficients):
        answer = answer * Q(value) + Q(coefficient)
    return answer


def first_nonzero_positive(vector: Sequence[int]) -> bool:
    """Choose one representative of ``v`` and ``-v``."""

    for value in vector:
        if value:
            return value > 0
    return False


def orbit_vectors(
    dimension: int,
    *,
    maximum_absolute_coefficient: int,
    maximum_l1_norm: int,
) -> tuple[tuple[int, ...], ...]:
    return tuple(
        vector
        for vector in coefficient_vectors(
            dimension,
            maximum_absolute_coefficient=maximum_absolute_coefficient,
            maximum_l1_norm=maximum_l1_norm,
        )
        if first_nonzero_positive(vector)
    )


@dataclass(frozen=True)
class AuxiliaryFermigierSlice:
    slice_id: str
    source_label: str
    slope: int
    intercept: Fraction
    source_x: Fraction
    source_y: Fraction
    quartic_coefficients: tuple[Fraction, ...]
    shifted_coefficients: tuple[Fraction, ...]
    weierstrass_coefficients: tuple[Fraction, ...]

    def quartic_value(self, parameter: Fraction) -> Fraction:
        return polynomial_value(self.quartic_coefficients, Q(parameter))

    def original_x(self, signed_parameter: Fraction) -> Fraction:
        return self.slope * Q(signed_parameter) + self.intercept

    def forward(
        self, point: tuple[Fraction, Fraction]
    ) -> tuple[Fraction, Fraction]:
        parameter, ordinate = (Q(value) for value in point)
        if ordinate**2 != self.quartic_value(parameter):
            raise ValueError("the point missed the auxiliary quartic")
        u_value = parameter - T0
        if u_value == 0:
            raise ValueError("the pointed base maps to infinity")
        _, d_value, c_value, _, _ = self.shifted_coefficients
        q_value = self.source_y
        x_value = (
            2 * q_value * (ordinate + q_value) + d_value * u_value
        ) / u_value**2
        y_value = (
            4 * q_value**2 * (ordinate + q_value)
            + 2 * q_value * (d_value * u_value + c_value * u_value**2)
            - d_value**2 * u_value**2 / (2 * q_value)
        ) / u_value**3
        image = x_value, y_value
        if not point_on_short_curve(self.weierstrass_coefficients, image):
            raise AssertionError("the exact pointed-quartic map failed")
        return image

    def inverse(
        self, point: tuple[Fraction, Fraction] | None
    ) -> tuple[Fraction, Fraction] | None:
        if point is None:
            return T0, self.source_y
        if not point_on_short_curve(self.weierstrass_coefficients, point):
            raise ValueError("the point missed the auxiliary Weierstrass model")
        x_value, y_value = point
        if y_value == 0:
            return None
        _, d_value, c_value, _, _ = self.shifted_coefficients
        q_value = self.source_y
        u_value = (
            4 * q_value**2 * (x_value + c_value) - d_value**2
        ) / (2 * q_value * y_value)
        if u_value == 0:
            return None
        ordinate = (
            (x_value * u_value**2 - d_value * u_value) / (2 * q_value)
            - q_value
        )
        parameter = T0 + u_value
        if ordinate**2 != self.quartic_value(parameter):
            raise AssertionError("the inverse pointed-quartic map failed")
        return parameter, ordinate


def make_auxiliary_slice(slice_data: Any) -> AuxiliaryFermigierSlice:
    coefficients = tuple(Q(value) for value in slice_data.coefficients)
    shifted = translate_polynomial(coefficients, T0)
    q_value = Q(slice_data.source_point[1])
    if len(shifted) != 5 or shifted[0] != q_value**2:
        raise AssertionError("the source point missed its auxiliary quartic")
    _, d_value, c_value, b_value, a_value = shifted
    weierstrass = (
        d_value / q_value,
        c_value - d_value**2 / (4 * q_value**2),
        2 * q_value * b_value,
        -4 * q_value**2 * a_value,
        a_value * (d_value**2 - 4 * q_value**2 * c_value),
    )
    return AuxiliaryFermigierSlice(
        slice_id=slice_data.identifier,
        source_label=slice_data.accidental_label,
        slope=int(slice_data.slope),
        intercept=Q(slice_data.intercept),
        source_x=Q(slice_data.source_point[0]),
        source_y=q_value,
        quartic_coefficients=coefficients,
        shifted_coefficients=shifted,
        weierstrass_coefficients=weierstrass,
    )


GENERIC_SECTION_LINES = tuple(
    (Q(sign), Q(root), f"visible-{root}-{'plus' if sign == 1 else 'minus'}")
    for root in ROOTS
    for sign in (-1, 1)
) + ((Q(-17, 35), Q(1256, 5), "Mestre-extra"),)


def generic_intersections(
    auxiliary: AuxiliaryFermigierSlice,
) -> tuple[tuple[Fraction, tuple[str, ...]], ...]:
    found: dict[Fraction, set[str]] = {}
    for slope, intercept, label in GENERIC_SECTION_LINES:
        if slope == auxiliary.slope:
            if intercept == auxiliary.intercept:
                raise AssertionError("an accidental slice became a generic section")
            continue
        parameter = Q(
            intercept - auxiliary.intercept,
            auxiliary.slope - slope,
        )
        square_root = rational_square_root(auxiliary.quartic_value(parameter))
        if square_root is None:
            raise AssertionError("a generic section intersection was not rational")
        found.setdefault(parameter, set()).add(label)
    return tuple(
        (parameter, tuple(sorted(labels)))
        for parameter, labels in sorted(
            found.items(), key=lambda item: (projective_height(item[0]), item[0])
        )
    )


def exact_seed_points(
    auxiliary: AuxiliaryFermigierSlice,
) -> tuple[tuple[tuple[Fraction, Fraction], ...], tuple[dict[str, Any], ...]]:
    points: list[tuple[Fraction, Fraction]] = []
    records = []
    for parameter, labels in generic_intersections(auxiliary):
        ordinate = rational_square_root(auxiliary.quartic_value(parameter))
        if ordinate is None:
            raise AssertionError("a generic ordinate disappeared")
        images = []
        if parameter != T0:
            for signed_ordinate in (ordinate, -ordinate):
                image = auxiliary.forward((parameter, signed_ordinate))
                if image not in points:
                    points.append(image)
                images.append(image)
        records.append(
            {
                "parameter_t": rational_to_string(parameter),
                "section_labels": list(labels),
                "mapped_sign_count": len(images),
            }
        )
    return tuple(points), tuple(records)


def saturate_basis(
    coefficients: Sequence[Fraction],
    basis: Sequence[tuple[Fraction, Fraction]],
    *,
    timeout: float,
    stack_bytes: int,
) -> tuple[tuple[tuple[Fraction, Fraction], ...], dict[str, Any]]:
    curve = ",".join(gp_rational(Q(value)) for value in coefficients)
    points = ",".join(gp_vector(point) for point in basis)
    program = "\n".join(
        (
            f"E=ellinit([{curve}]);K=[{points}];",
            "default(realprecision,120);",
            "D0=matdet(ellheightmatrix(E,K));W=ellsaturation(E,K,20);",
            "D1=matdet(ellheightmatrix(E,W));SI=round(sqrt(D0/D1));",
            'print("SATURATION ",SI,"|",W,"|",D1);',
            "quit",
            "",
        )
    )
    try:
        output, wall_seconds = run_gp(
            program, timeout=timeout, stack_bytes=stack_bytes
        )
    except Exception as error:
        return tuple(basis), {
            "status": "failed",
            "error": str(error)[:500],
            "fallback_used": "unsaturated exact independent basis",
        }
    match = re.search(r"SATURATION (\d+)\|(.*?)\|([^|\n]+)$", output, re.MULTILINE)
    if match is None:
        raise AssertionError("PARI omitted saturation markers")
    parsed = parse_gp_exact(match.group(2))
    saturated = tuple((Q(point[0]), Q(point[1])) for point in parsed)
    if len(saturated) != len(basis) or any(
        not point_on_short_curve(coefficients, point) for point in saturated
    ):
        raise AssertionError("the saturated auxiliary basis failed exact replay")
    return saturated, {
        "status": "completed",
        "prime_bound": 20,
        "index_improvement": int(match.group(1)),
        "height_determinant": match.group(3),
        "wall_seconds": wall_seconds,
        "basis_point_sha256": point_digest(saturated),
    }


def prior_parameter_manifest(
    artifact_directory: Path,
) -> tuple[set[Fraction], dict[str, Any]]:
    manifest_path = artifact_directory / PRIOR_MANIFEST_ARTIFACT
    if file_sha256(manifest_path) != EXPECTED_MANIFEST_ARTIFACT_SHA256:
        raise AssertionError("the pinned prior-manifest artifact changed")
    manifest = json.loads(manifest_path.read_text())
    source_rows = manifest["prior_decontamination"]["artifact_sources"]
    parameters = {abs(T0), *(abs(value) for value in LEGACY_ACCIDENTAL_PARAMETERS)}
    replayed = {}
    for name, source in sorted(source_rows.items()):
        path = artifact_directory / name
        observed = file_sha256(path)
        if observed != source["sha256"]:
            raise AssertionError(f"pinned prior source changed: {name}")
        extracted = extract_parameter_values(json.loads(path.read_text()))
        parameters.update(extracted)
        replayed[name] = {
            "sha256": observed,
            "extracted_parameter_count": len(extracted),
        }
    digest = rational_digest(sorted(parameters))
    if (
        len(parameters) != EXPECTED_PRIOR_PARAMETER_COUNT
        or digest != EXPECTED_PRIOR_PARAMETER_SHA256
    ):
        raise AssertionError("the pinned prior parameter population changed")
    return parameters, {
        "manifest_artifact": str(manifest_path),
        "manifest_artifact_sha256": EXPECTED_MANIFEST_ARTIFACT_SHA256,
        "unique_parameter_count": len(parameters),
        "parameter_sha256": digest,
        "source_artifacts": replayed,
    }


def linear_combination(
    coefficients: Sequence[Fraction],
    basis: Sequence[tuple[Fraction, Fraction]],
    vector: Sequence[int],
) -> tuple[Fraction, Fraction] | None:
    answer = None
    for point, scalar in zip(basis, vector, strict=True):
        if scalar:
            answer = weierstrass_add(
                coefficients,
                answer,
                weierstrass_multiply(coefficients, point, scalar),
            )
    return answer


@dataclass
class CandidateIncidence:
    source_labels: set[str]
    slice_ids: set[str]
    first_slice_id: str
    first_vector: tuple[int, ...]
    signed_parameter: Fraction
    ordinate: Fraction


def generate_orbits(
    auxiliaries: Sequence[AuxiliaryFermigierSlice],
    bases: dict[str, tuple[tuple[Fraction, Fraction], ...]],
    prior_parameters: set[Fraction],
    *,
    maximum_absolute_coefficient: int,
    maximum_l1_norm: int,
) -> tuple[dict[Fraction, CandidateIncidence], list[dict[str, Any]], dict[str, int]]:
    generic = {
        abs(parameter)
        for auxiliary in auxiliaries
        for parameter, _ in generic_intersections(auxiliary)
    }
    candidates: dict[Fraction, CandidateIncidence] = {}
    slice_records = []
    totals = {
        "coefficient_vectors": 0,
        "exceptional_inverse_images": 0,
        "record_or_zero": 0,
        "generic_intersections": 0,
        "prior_parameters": 0,
        "singular_parameters": 0,
        "accepted_incidences": 0,
    }
    for auxiliary in auxiliaries:
        basis = bases[auxiliary.slice_id]
        vectors = orbit_vectors(
            len(basis),
            maximum_absolute_coefficient=maximum_absolute_coefficient,
            maximum_l1_norm=maximum_l1_norm,
        )
        accepted = 0
        for vector in vectors:
            totals["coefficient_vectors"] += 1
            point = linear_combination(
                auxiliary.weierstrass_coefficients, basis, vector
            )
            inverse = auxiliary.inverse(point)
            if inverse is None:
                totals["exceptional_inverse_images"] += 1
                continue
            signed_parameter, ordinate = inverse
            parameter = abs(signed_parameter)
            if parameter in (Q(0), abs(T0)):
                totals["record_or_zero"] += 1
                continue
            if parameter in generic:
                totals["generic_intersections"] += 1
                continue
            if parameter in prior_parameters:
                totals["prior_parameters"] += 1
                continue
            if FermigierMestreFamily.discriminant_factor(parameter) == 0:
                totals["singular_parameters"] += 1
                continue
            x_value = auxiliary.original_x(signed_parameter)
            if ordinate**2 != FermigierMestreFamily.quartic_value(
                parameter, x_value
            ):
                raise AssertionError("an orbit point missed the canonical Fermigier fiber")
            existing = candidates.get(parameter)
            if existing is None:
                candidates[parameter] = CandidateIncidence(
                    source_labels={auxiliary.source_label},
                    slice_ids={auxiliary.slice_id},
                    first_slice_id=auxiliary.slice_id,
                    first_vector=tuple(vector),
                    signed_parameter=signed_parameter,
                    ordinate=ordinate,
                )
            else:
                existing.source_labels.add(auxiliary.source_label)
                existing.slice_ids.add(auxiliary.slice_id)
            accepted += 1
            totals["accepted_incidences"] += 1
        slice_records.append(
            {
                "slice_id": auxiliary.slice_id,
                "source_label": auxiliary.source_label,
                "basis_rank": len(basis),
                "sign_quotiented_vector_count": len(vectors),
                "accepted_incidence_count": accepted,
            }
        )
        print(
            f"orbit {auxiliary.slice_id}: vectors={len(vectors)} "
            f"accepted={accepted} unique_global={len(candidates)}",
            flush=True,
        )
    totals["unique_parameters"] = len(candidates)
    totals["multiple_source_parameters"] = sum(
        len(record.source_labels) >= 2 for record in candidates.values()
    )
    return candidates, slice_records, totals


def homogenized_discriminant_factor(parameter: Fraction) -> int:
    parameter = Q(parameter)
    numerator, denominator = parameter.numerator, parameter.denominator
    degree = len(DISCRIMINANT_FACTOR_COEFFICIENTS) - 1
    return sum(
        int(coefficient)
        * numerator**power
        * denominator ** (degree - power)
        for power, coefficient in enumerate(DISCRIMINANT_FACTOR_COEFFICIENTS)
    )


def primes_up_to(bound: int) -> tuple[int, ...]:
    if bound < 2:
        return ()
    sieve = bytearray(b"\x01") * (bound + 1)
    sieve[:2] = b"\x00\x00"
    for value in range(2, isqrt(bound) + 1):
        if sieve[value]:
            sieve[value * value : bound + 1 : value] = b"\x00" * (
                (bound - value * value) // value + 1
            )
    return tuple(index for index, flag in enumerate(sieve) if flag)


def radical_upper_proxy(
    parameter: Fraction, *, prime_bound: int
) -> dict[str, Any]:
    parameter = Q(parameter)
    remaining = abs(homogenized_discriminant_factor(parameter))
    denominator_remaining = parameter.denominator
    support = {2, 3}
    valuations = {}
    for prime in primes_up_to(prime_bound):
        valuation = 0
        while remaining % prime == 0:
            remaining //= prime
            valuation += 1
        if valuation:
            support.add(prime)
            valuations[str(prime)] = valuation
        while denominator_remaining % prime == 0:
            denominator_remaining //= prime
            support.add(prime)
    log_upper = sum(log(prime) for prime in support)
    if remaining > 1:
        log_upper += log(remaining)
    if denominator_remaining > 1:
        log_upper += log(denominator_remaining)
    return {
        "log_radical_upper_proxy": log_upper,
        "trial_prime_bound": prime_bound,
        "small_prime_valuations": valuations,
        "unfactored_discriminant_cofactor_digits": len(str(remaining)),
        "unfactored_denominator_cofactor": denominator_remaining,
    }


def candidate_stream_digest(parameters: Iterable[Fraction]) -> str:
    digest = hashlib.sha256()
    for parameter in sorted(
        parameters,
        key=lambda value: (
            projective_height(value),
            value.numerator,
            value.denominator,
        ),
    ):
        digest.update((rational_to_string(parameter) + "\n").encode())
    return digest.hexdigest()


def selected_proxy_records(
    candidates: dict[Fraction, CandidateIncidence],
    *,
    prime_bound: int,
    score_bound: int,
    keep: int,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    tables = build_score_tables(score_bound, "fermigier-good")
    # Keep a bounded heap while still evaluating every generated parameter.
    heap: list[tuple[float, int, int, int, Fraction, dict[str, Any]]] = []
    minimum_proxy = float("inf")
    below_190 = 0
    for index, (parameter, incidence) in enumerate(candidates.items(), start=1):
        proxy = radical_upper_proxy(parameter, prime_bound=prime_bound)
        proxy_value = float(proxy["log_radical_upper_proxy"])
        minimum_proxy = min(minimum_proxy, proxy_value)
        if proxy_value < 190.0:
            below_190 += 1
        score = score_rational(
            parameter.numerator, parameter.denominator, tables
        )
        record = {
            "parameter_t": rational_to_string(parameter),
            "projective_height": projective_height(parameter),
            "source_labels": sorted(incidence.source_labels),
            "slice_ids": sorted(incidence.slice_ids),
            "first_slice_id": incidence.first_slice_id,
            "first_coefficient_vector": list(incidence.first_vector),
            "signed_parameter_t": rational_to_string(incidence.signed_parameter),
            "ordinate": rational_to_string(incidence.ordinate),
            "radical_proxy": proxy,
            "good_prime_score_B200": score,
        }
        # The heap root is the worst retained key.  Negating the desired
        # ascending key avoids materializing proxy records for every orbit.
        key = (
            -proxy_value,
            -len(incidence.source_labels),
            -projective_height(parameter),
            -parameter.numerator,
            parameter,
            record,
        )
        if len(heap) < keep:
            heapq.heappush(heap, key)
        elif key > heap[0]:
            heapq.heapreplace(heap, key)
        if index % 10_000 == 0:
            print(
                f"proxy {index}/{len(candidates)} minimum={minimum_proxy:.6f} "
                f"below190={below_190}",
                flush=True,
            )
    records = [item[-1] for item in heap]
    records.sort(
        key=lambda record: (
            record["radical_proxy"]["log_radical_upper_proxy"],
            -len(record["source_labels"]),
            -record["good_prime_score_B200"]["value"],
            record["projective_height"],
            Q(record["parameter_t"]),
        )
    )
    return records, {
        "evaluated_parameter_count": len(candidates),
        "minimum_log_radical_upper_proxy": minimum_proxy,
        "proxy_below_190_count": below_190,
        "retained_count": len(records),
        "score_bound": score_bound,
        "proxy_prime_bound": prime_bound,
    }


def conductor_selection(
    proxy_records: Sequence[dict[str, Any]], *, keep: int
) -> list[dict[str, Any]]:
    feasible = [
        record
        for record in proxy_records
        if record["radical_proxy"]["log_radical_upper_proxy"] < 195.0
    ]
    selected: dict[str, dict[str, Any]] = {}
    for record in feasible[: keep // 2]:
        selected[record["parameter_t"]] = record
    for record in sorted(
        feasible,
        key=lambda item: (
            -item["good_prime_score_B200"]["value"],
            item["radical_proxy"]["log_radical_upper_proxy"],
            item["projective_height"],
        ),
    )[:keep]:
        selected.setdefault(record["parameter_t"], record)
        if len(selected) >= keep:
            break
    return sorted(
        selected.values(),
        key=lambda item: (
            item["radical_proxy"]["log_radical_upper_proxy"],
            -item["good_prime_score_B200"]["value"],
            item["projective_height"],
        ),
    )



def on_curve(point):
    x, y = point
    a1, a2, a3, a4, a6 = GENERAL_WEIERSTRASS_COEFFICIENTS
    return y * y + a1 * x * y + a3 * y == (
        x**3 + a2 * x**2 + a4 * x + a6
    )


def c4():
    a1, a2, a3, a4, _a6 = GENERAL_WEIERSTRASS_COEFFICIENTS
    b2 = a1 * a1 + 4 * a2
    b4 = 2 * a4 + a1 * a3
    return b2 * b2 - 24 * b4


def c6():
    a1, a2, a3, a4, a6 = GENERAL_WEIERSTRASS_COEFFICIENTS
    b2 = a1 * a1 + 4 * a2
    b4 = 2 * a4 + a1 * a3
    b6 = a3 * a3 + 4 * a6
    return -b2**3 + 36 * b2 * b4 - 216 * b6


def short_coefficients():
    return (Q(0), Q(0), Q(0), Q(-27 * c4()), Q(-54 * c6()))


def to_short(point):
    x, y = point
    a1, a2, a3, _a4, _a6 = GENERAL_WEIERSTRASS_COEFFICIENTS
    b2 = a1 * a1 + 4 * a2
    return 36 * x + 3 * b2, 108 * (2 * y + a1 * x + a3)



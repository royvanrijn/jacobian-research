ZERO = (Fraction(0),) * 5
ONE = (Fraction(1), Fraction(0), Fraction(0), Fraction(0), Fraction(0))


def add(a, b):
    return tuple(x + y for x, y in zip(a, b))


def scale(a, c):
    c = Fraction(c)
    return tuple(c * x for x in a)


def mul(a, b):
    raw = [Fraction(0) for _ in range(9)]
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b):
                if y:
                    raw[i + j] += x * y
    # Normalize h to q^5 = -sum_{i<5} H[i]/H[5] q^i.
    for degree in range(8, 4, -1):
        lead = raw[degree]
        if not lead:
            continue
        raw[degree] = 0
        shift = degree - 5
        for i in range(5):
            raw[shift + i] -= lead * Fraction(H[i], H[5])
    return tuple(raw[:5])


def power(a, n):
    out, base = ONE, a
    while n:
        if n & 1:
            out = mul(out, base)
        base = mul(base, base)
        n >>= 1
    return out


def q_poly(coeffs):
    out = [Fraction(0)] * 5
    for i, c in enumerate(coeffs):
        if i >= 5:
            raise ValueError("use quotient reduction for degree >=5")
        out[i] = Fraction(c)
    return tuple(out)


def graph_value(name):
    denominator, numerators = GRAPH[name]
    # numerators index q^1,...,q^5; reduce q^5 in the quotient.
    qelt = q_poly([0, 1, 0, 0, 0])
    out, qp = ZERO, ONE
    for degree in range(1, 6):
        qp = mul(qp, qelt)
        out = add(out, scale(qp, Fraction(numerators[degree - 1], denominator)))
    return out


def parse_equations():
    q, x2, x3, x4, x5, x6 = sp.symbols("q x2 x3 x4 x5 x6")
    local = {str(v): v for v in (q, x2, x3, x4, x5, x6)}
    equations = []
    for line in EQ_FILE.read_text().splitlines():
        if re.match(r"F\d+ = ", line):
            equations.append(sp.Poly(sp.sympify(line.split("=", 1)[1], locals=local), q, x2, x3, x4, x5, x6, domain=sp.ZZ))
    return (q, x2, x3, x4, x5, x6), equations


def write_lex_file():
    lines = [
        "# Exact lexicographic graph on the mu_7 quotient",
        "# q=u^7 and x_i=a_i*u^(i-1); q is nonzero on the first-block locus.",
        "H = " + " + ".join(f"({c})*q^{i}" for i, c in enumerate(H) if c),
    ]
    for name in ("x2", "x3", "x4", "x5", "x6"):
        denominator, nums = GRAPH[name]
        rhs = " + ".join(f"({c})*q^{i}" for i, c in enumerate(nums, 1))
        lines.append(f"G_{name} = ({denominator})*{name} - ({rhs})")
    LEX_FILE.write_text("\n".join(lines) + "\n")


def main():
    variables, equations = parse_equations()
    q, *xs = variables
    values = {
        q: q_poly([0, 1, 0, 0, 0]),
        **{symbol: graph_value(str(symbol)) for symbol in xs},
    }
    for index, polynomial in enumerate(equations, 1):
        total = ZERO
        for monomial, coefficient in polynomial.terms():
            term = ONE
            for variable, exponent in zip(variables, monomial):
                term = mul(term, power(values[variable], exponent))
            total = add(total, scale(term, int(coefficient)))
        if total != ZERO:
            raise RuntimeError(f"quotient equation F{index} has nonzero graph residual")
        print(f"F{index}_GRAPH_RESIDUAL_ZERO")
    write_lex_file()
    print("QUOTIENT_GRAPH_EXACT_PASS")
    print(f"LEX_FILE={LEX_FILE.name}")


if __name__ == "__main__":
    main()

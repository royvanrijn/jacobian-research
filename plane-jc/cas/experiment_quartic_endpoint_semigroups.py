#!/usr/bin/env python3
"""Bounded quartic cusp/connector endpoint-semigroup experiment.

This checker compiles the endpoint data which are currently proved for the
clean one-boundary quartic packet.  It deliberately does not report a Keller
map or a quartic exclusion.  The connector count, displayed pole parameter,
and local odd-square contact are user-supplied bounds; the mathematics does
not presently bound them in terms of geometric degree four.

For a connector

    d_{n,lambda} = x*y - y^(n+1) - lambda

the normalization is

    x = t^n + lambda*t^-1,  y = t.

The displayed *polar-bound* monoid is generated by (1,n) and (0,1).
Pole vectors themselves are not additive when zeros cancel poles.  The
residue-aware identity x-y^n=lambda*t^-1 shows that the realized pole-vector
set is N^2.  Equivalently, the exact signed two-endpoint valuation semigroup
of k[t,t^-1] is {(u,v):u+v<=0}.  Conductor pairing and local odd-square
contact are recorded separately, because neither is determined by the
numerical displayed bounds.
"""
from __future__ import annotations

import argparse
import itertools
import json
import math
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Iterable


Permutation = tuple[int, ...]
PoleVector = tuple[int, int]


def compose(left: Permutation, right: Permutation) -> Permutation:
    """Return left after right."""

    return tuple(left[right[index]] for index in range(len(left)))


def inverse(permutation: Permutation) -> Permutation:
    result = [0] * len(permutation)
    for source, target in enumerate(permutation):
        result[target] = source
    return tuple(result)


def generated_group(generators: Iterable[Permutation]) -> frozenset[Permutation]:
    generators = tuple(generators)
    degree = len(generators[0])
    identity = tuple(range(degree))
    expanded = generators + tuple(inverse(item) for item in generators)
    group = {identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for generator in expanded:
            candidate = compose(generator, current)
            if candidate not in group:
                group.add(candidate)
                frontier.append(candidate)
    return frozenset(group)


def transpositions(degree: int) -> tuple[Permutation, ...]:
    result = []
    for left in range(degree):
        for right in range(left + 1, degree):
            permutation = list(range(degree))
            permutation[left], permutation[right] = (
                permutation[right],
                permutation[left],
            )
            result.append(tuple(permutation))
    return tuple(result)


def cusp_braid_pairs() -> tuple[tuple[Permutation, Permutation], ...]:
    result = []
    for left in transpositions(4):
        for right in transpositions(4):
            if left == right:
                continue
            if compose(left, compose(right, left)) == compose(
                right, compose(left, right)
            ):
                result.append((left, right))
    return tuple(result)


def perfect_matchings() -> tuple[tuple[Permutation, Permutation], ...]:
    result = []
    for left, right in itertools.combinations(transpositions(4), 2):
        if compose(left, right) == compose(right, left):
            result.append((left, right))
    return tuple(result)


def double_factorial_odd(connector_count: int) -> int:
    """Return (2r-1)!!, with the empty matching counted once."""

    return math.prod(range(1, 2 * connector_count, 2))


def endpoint_pairings(
    connector_count: int,
) -> tuple[tuple[tuple[int, int], ...], ...]:
    """Enumerate every perfect matching of 2r labeled normalized endpoints."""

    def recurse(
        remaining: tuple[int, ...],
    ) -> tuple[tuple[tuple[int, int], ...], ...]:
        if not remaining:
            return ((),)
        first = remaining[0]
        result = []
        for index in range(1, len(remaining)):
            second = remaining[index]
            tail = remaining[1:index] + remaining[index + 1 :]
            for following in recurse(tail):
                result.append(((first, second),) + following)
        return tuple(result)

    pairings = recurse(tuple(range(2 * connector_count)))
    assert len(pairings) == double_factorial_odd(connector_count)
    return pairings


def numerical_semigroup_contains_2_3(value: int) -> bool:
    return value == 0 or value >= 2


def displayed_connector_contains(vector: PoleVector, n: int) -> bool:
    """Membership in N*(1,n)+N*(0,1)."""

    first, second = vector
    return first >= 0 and second >= n * first


def connector_holes(n: int, cutoff: int) -> tuple[PoleVector, ...]:
    """Points of N^2 in a finite box missed by the displayed monoid."""

    return tuple(
        (first, second)
        for first in range(cutoff + 1)
        for second in range(cutoff + 1)
        if not displayed_connector_contains((first, second), n)
    )


@dataclass(frozen=True)
class ConnectorSemigroup:
    n: int
    displayed_polar_bound_generators: tuple[PoleVector, PoleVector]
    cancellation_identity: str
    completed_polar_bound_generators: tuple[PoleVector, PoleVector]
    displayed_polar_bound_holes_in_box: tuple[PoleVector, ...]
    displayed_polar_bound_has_conductor_in_n2: bool
    completed_polar_bound_conductor: PoleVector
    signed_valuation_semigroup_generators: tuple[PoleVector, ...]
    signed_valuation_semigroup: str
    realized_pole_vector_set: str
    normalization_ring: str
    normalization_conductor: str
    conductor_endpoint_exponents: PoleVector


@dataclass(frozen=True)
class FeasibilityRow:
    connector_count: int
    displayed_pole_bound: int
    contact_bound: int
    cusp_braid_choices: int
    sheet_matching_choices_per_connector: int
    endpoint_pairing_choices: int
    endpoint_pairings: tuple[tuple[tuple[int, int], ...], ...]
    pole_parameter_choices: int
    contact_parameter_choices: int
    feasible_decorated_records: int
    odd_square_vector_shape: str
    all_sheet_records_generate_s4: bool
    status: str


def connector_record(n: int, cutoff: int) -> ConnectorSemigroup:
    holes = connector_holes(n, cutoff)
    assert (1, 0) in holes
    # There is no conductor c with c+N^2 contained in the displayed monoid:
    # for every c, increasing only its first coordinate eventually violates
    # second >= n*first.
    return ConnectorSemigroup(
        n=n,
        displayed_polar_bound_generators=((1, n), (0, 1)),
        cancellation_identity="(x-y^n)/lambda=t^-1",
        completed_polar_bound_generators=((1, 0), (0, 1)),
        displayed_polar_bound_holes_in_box=holes,
        displayed_polar_bound_has_conductor_in_n2=False,
        completed_polar_bound_conductor=(0, 0),
        signed_valuation_semigroup_generators=(
            (1, -1),
            (-1, 1),
            (0, -1),
        ),
        signed_valuation_semigroup="{(u,v) in Z^2 : u+v<=0}",
        realized_pole_vector_set=(
            "N^2; pole vectors form a set, not an additive valuation map"
        ),
        normalization_ring="k[t,t^-1]",
        normalization_conductor="unit ideal (the connector is normal)",
        conductor_endpoint_exponents=(1, 1),
    )


def sheet_audit() -> dict[str, object]:
    cusp_pairs = cusp_braid_pairs()
    matchings = perfect_matchings()
    group_orders = {
        len(generated_group((*cusp_pair, *matching)))
        for cusp_pair in cusp_pairs
        for matching in matchings
    }
    assert len(cusp_pairs) == 24
    assert len(matchings) == 3
    assert group_orders == {24}
    return {
        "nondegenerate_cusp_braid_pairs": len(cusp_pairs),
        "cusp_braid_pair_atlas": cusp_pairs,
        "connector_perfect_matchings": len(matchings),
        "connector_sheet_matching_atlas": matchings,
        "one_connector_records": len(cusp_pairs) * len(matchings),
        "generated_group_orders": sorted(group_orders),
        "verdict": "every one-connector sheet record generates S4",
    }


def feasibility_row(
    connector_count: int, pole_bound: int, contact_bound: int
) -> FeasibilityRow:
    cusp_choices = len(cusp_braid_pairs())
    matching_choices = len(perfect_matchings())
    pairing_atlas = endpoint_pairings(connector_count)
    endpoint_pairing_count = len(pairing_atlas)
    pole_choices = pole_bound**connector_count
    contact_choices = contact_bound**connector_count
    feasible = (
        cusp_choices
        * matching_choices**connector_count
        * endpoint_pairing_count
        * pole_choices
        * contact_choices
    )
    return FeasibilityRow(
        connector_count=connector_count,
        displayed_pole_bound=pole_bound,
        contact_bound=contact_bound,
        cusp_braid_choices=cusp_choices,
        sheet_matching_choices_per_connector=matching_choices,
        endpoint_pairing_choices=endpoint_pairing_count,
        endpoint_pairings=pairing_atlas,
        pole_parameter_choices=pole_choices,
        contact_parameter_choices=contact_choices,
        feasible_decorated_records=feasible,
        odd_square_vector_shape=(
            "(2,m_1,m_1,...,m_r,m_r), 1<=m_i<=contact_bound"
        ),
        all_sheet_records_generate_s4=True,
        status="formally_feasible_not_a_quartic_normalization",
    )


def bridge_audit(cutoff: int) -> dict[str, object]:
    pieces = {}
    for degree in range(-cutoff, cutoff + 1):
        if degree >= 0:
            generator = f"s^{degree}"
        elif degree % 2 == 0:
            generator = f"a^{(-degree) // 2}"
        else:
            generator = f"a^{(1 - degree) // 2}*s"
        pieces[str(degree)] = generator
    return {
        "degree_zero_ring": "k[x,y]",
        "ambient_factorial": True,
        "graded_piece_generators": pieces,
        "all_checked_pieces_rank_one_free": True,
        "odd_square_identity": "(a*s)^2=h*a",
        "odd_square_cokernel": "k[x,y]/(h)",
        "cusp_semigroup_generators": [2, 3],
        "cusp_semigroup_holes": [
            value
            for value in range(cutoff + 1)
            if not numerical_semigroup_contains_2_3(value)
        ],
        "cusp_conductor_exponent": 2,
        "cusp_odd_square_contact": 2,
    }


def build_report(
    max_connectors: int,
    max_pole: int,
    max_contact: int,
    cutoff: int,
) -> dict[str, object]:
    if min(max_connectors, max_pole, max_contact, cutoff) < 1:
        raise ValueError("all bounds must be positive")
    return {
        "claim": (
            "bounded feasibility only; the inputs do not supply these bounds"
        ),
        "bounds": {
            "max_connectors": max_connectors,
            "max_displayed_pole_parameter": max_pole,
            "max_odd_square_contact": max_contact,
            "semigroup_box_cutoff": cutoff,
        },
        "uniform_endpoint_carrier": {
            "equation": (
                "(y^2-x^3)*product_i(x*y-y^(n_i+1)-lambda_i)"
            ),
            "connector_normalization": (
                "x=t^n+lambda*t^-1, y=t, lambda!=0"
            ),
            "connector_count": "arbitrary",
            "displayed_pole_parameter": "arbitrary n>=1",
            "local_connector_contact": "arbitrary m>=1 in the completed chart",
            "warning": (
                "the conductor pairing is decoration from the finite map; "
                "the carrier is not a quartic finite normalization or Keller map"
            ),
        },
        "sheet_monodromy": sheet_audit(),
        "bridge": bridge_audit(cutoff),
        "connector_semigroups": [
            asdict(connector_record(n, cutoff))
            for n in range(1, max_pole + 1)
        ],
        "feasibility_rows": [
            asdict(feasibility_row(count, max_pole, max_contact))
            for count in range(1, max_connectors + 1)
        ],
        "global_verdict": {
            "finite_after_external_bounds": True,
            "degree_four_bound_proved": False,
            "packet_excluded": False,
            "packet_model_realized": False,
            "reason": (
                "connector count, minimized-height bound, and connector "
                "contact bound are not consequences of the compiled inputs"
            ),
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-connectors", type=int, default=4)
    parser.add_argument("--max-pole", type=int, default=8)
    parser.add_argument("--max-contact", type=int, default=8)
    parser.add_argument("--cutoff", type=int, default=12)
    parser.add_argument("--output", type=Path)
    arguments = parser.parse_args()
    report = build_report(
        arguments.max_connectors,
        arguments.max_pole,
        arguments.max_contact,
        arguments.cutoff,
    )
    rendered = json.dumps(report, indent=2, sort_keys=True) + "\n"
    if arguments.output:
        arguments.output.parent.mkdir(parents=True, exist_ok=True)
        arguments.output.write_text(rendered)
    print(rendered, end="")


if __name__ == "__main__":
    main()
